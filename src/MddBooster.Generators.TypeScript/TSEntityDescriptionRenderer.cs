using System.Text;
using M3L.Native;
using MddBooster.Core.Generation;
using MddBooster.Core.Naming;
using MddBooster.Core.Semantic;

namespace MddBooster.Generators.TypeScript;

/// <summary>
/// Renders <c>entity_description_gen.ts</c>: every entity's fields as data, in sections, in reading order — what a generated form
/// knows about the entity, offered to any screen that shows it (a detail view, a print, an audit trail) so none of them writes
/// the same list of labels again.
/// </summary>
/// <remarks>
/// <para>
/// This is the reading side. <c>field_schema_gen.ts</c> is the writing side — constraints, for a consumer that checks input — and
/// stays as it is; nothing here says <c>required</c>, <c>maxLength</c>, <c>min</c> or <c>max</c>.
/// </para>
/// <para>
/// Everything is read from the model and nothing is made up: the label is the one the form uses (the author's, else the field's
/// name in PascalCase), the hint is <c>@help</c>, the sections are the form's (<see cref="EntitySections"/>), a reference names the
/// entity it points at, and a lookup names the reference it reads through. The model has no notion of which column of a target
/// "names" it, so no such thing is emitted.
/// </para>
/// </remarks>
public static class TSEntityDescriptionRenderer
{
    private const string Header = "// <auto-generated> mdd-booster; DO NOT EDIT.</auto-generated>";

    public static string RenderAll(IReadOnlyList<ResolvedModel> models, IReadOnlySet<string> enumNames)
    {
        ArgumentNullException.ThrowIfNull(models);
        ArgumentNullException.ThrowIfNull(enumNames);

        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine();
        sb.AppendLine("export type FieldKind =");
        sb.AppendLine("  | 'text' | 'number' | 'boolean' | 'date' | 'time' | 'datetime' | 'json' | 'binary'");
        sb.AppendLine("  | 'enum' | 'reference'");
        sb.AppendLine();
        sb.AppendLine("export type FieldDescription = {");
        sb.AppendLine("  name: string");
        sb.AppendLine("  label: string");
        sb.AppendLine("  hint?: string");
        sb.AppendLine("  kind: FieldKind");
        sb.AppendLine("  list?: true");
        sb.AppendLine("  enum?: string");
        sb.AppendLine("  reference?: string");
        sb.AppendLine("  via?: string");
        sb.AppendLine("  derived?: 'lookup' | 'rollup' | 'computed'");
        sb.AppendLine("  readOnly?: true");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export type SectionDescription = {");
        sb.AppendLine("  title?: string");
        sb.AppendLine("  fields: readonly FieldDescription[]");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export type EntityDescription = {");
        sb.AppendLine("  sections: readonly SectionDescription[]");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export const EntityDescriptions = {");

        foreach (var model in models)
        {
            var fields = model.Fields
                .Where(f => f.Kind is FieldKind.Stored or FieldKind.Lookup or FieldKind.Rollup or FieldKind.Computed)
                .Where(f => !EntitySurface.IsFieldInternal(f))
                .Where(f => !MddBooster.Core.Ast.FieldAttributes.Has(f, "pk"))
                .ToList();
            if (fields.Count == 0) continue;

            var (sections, untitledDefault) = EntitySections.Group(fields);

            sb.Append("  ").Append(NameCasing.ToPascalCase(model.Name)).AppendLine(": {");
            sb.AppendLine("    sections: [");
            foreach (var section in sections)
            {
                sb.Append("      { ");
                if (!untitledDefault)
                    sb.Append("title: ").Append(SourceLiteral.TypeScriptString(section.Name)).Append(", ");
                sb.AppendLine("fields: [");
                foreach (var field in section.Fields)
                    sb.Append("        ").Append(Describe(field, model, models, enumNames)).AppendLine(",");
                sb.AppendLine("      ] },");
            }
            sb.AppendLine("    ],");
            sb.AppendLine("  },");
        }

        sb.AppendLine("} as const satisfies Record<string, EntityDescription>");
        sb.AppendLine();
        return sb.ToString();
    }

    private static string Describe(
        FieldNode field,
        ResolvedModel owner,
        IReadOnlyList<ResolvedModel> allModels,
        IReadOnlySet<string> enumNames)
    {
        var parts = new List<string>
        {
            $"name: {SourceLiteral.TypeScriptString(NameCasing.ToPascalCase(field.Name))}",
            // The label a form shows: the author's (a lookup borrowing its target's), else the field's name — the same fallback.
            $"label: {SourceLiteral.TypeScriptString(FieldLabels.Authored(field, owner, allModels) ?? NameCasing.ToPascalCase(field.Name))}",
        };

        if (MddBooster.Core.Ast.FieldAttributes.FirstArg(field, "help") is { Length: > 0 } hint)
            parts.Add($"hint: {SourceLiteral.TypeScriptString(hint)}");

        var (kind, enumType, referenceTarget) = Classify(field, enumNames);
        parts.Add($"kind: '{kind}'");
        if (field.Array) parts.Add("list: true");
        if (enumType is not null) parts.Add($"enum: {SourceLiteral.TypeScriptString(enumType)}");
        if (referenceTarget is not null) parts.Add($"reference: {SourceLiteral.TypeScriptString(referenceTarget)}");

        var derived = field.Kind switch
        {
            FieldKind.Lookup => "lookup",
            FieldKind.Rollup => "rollup",
            FieldKind.Computed => "computed",
            _ => null,
        };
        if (derived == "lookup"
            && LookupPath.TrySplit(field.Lookup?.Path, out var segments, out _)
            && segments.Count > 0)
        {
            // The reference on this entity the lookup starts from; a longer path continues through the targets.
            parts.Add($"via: {SourceLiteral.TypeScriptString(NameCasing.ToPascalCase(segments[0]))}");
        }
        if (derived is not null) parts.Add($"derived: '{derived}'");

        // Not typed in by a person: derived, written by the system or the engine (the row version), or the timestamps every
        // entity inherits — a form has no control for any of them.
        if (derived is not null || FieldAuthorship.IsSystemWritten(field) || IsInheritedTimestamp(field.Name))
            parts.Add("readOnly: true");

        return "{ " + string.Join(", ", parts) + " }";
    }

    private static (string Kind, string? EnumType, string? ReferenceTarget) Classify(FieldNode field, IReadOnlySet<string> enumNames)
    {
        if (MddBooster.Core.Ast.FieldAttributes.Has(field, "reference") && LookupPath.ReferenceTarget(field) is { } target)
            return ("reference", null, NameCasing.ToPascalCase(target));

        var type = field.Type ?? "string";
        if (enumNames.Contains(type))
            return ("enum", NameCasing.ToPascalCase(type), null);

        var baseType = type.Contains('(') ? type[..type.IndexOf('(')] : type;
        return (baseType switch
        {
            "integer" or "long" or "short" or "byte" or "float" or "double" or "decimal" => "number",
            "boolean" => "boolean",
            "date" => "date",
            "time" => "time",
            "timestamp" or "datetime" => "datetime",
            "json" => "json",
            "binary" or "rowversion" => "binary",
            _ => "text",
        }, null, null);
    }

    private static bool IsInheritedTimestamp(string fieldName) =>
        string.Equals(fieldName, "created_at", StringComparison.OrdinalIgnoreCase)
        || string.Equals(fieldName, "updated_at", StringComparison.OrdinalIgnoreCase);
}
