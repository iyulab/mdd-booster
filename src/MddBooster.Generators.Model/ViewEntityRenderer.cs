using System.Text;
using MddBooster.Core.Naming;
using MddBooster.Core.Semantic;

namespace MddBooster.Generators.Model;

/// <summary>
/// Renders the read entity of a standalone <c>::view</c> served as a read model: one class, its properties the view's
/// output columns. There is no write half — nothing is stored through a view — and no audit timestamps: the class
/// carries a key and what the view returns.
/// </summary>
public static class ViewEntityRenderer
{
    private const string Header = "// <auto-generated> mdd-booster; DO NOT EDIT.</auto-generated>";

    public static string Render(ResolvedView view, string ns, IReadOnlySet<string>? knownEnumNames, bool postgres = false)
    {
        ArgumentNullException.ThrowIfNull(view);
        ArgumentException.ThrowIfNullOrWhiteSpace(ns);

        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        if (view.Columns.Any(c => c.Field.Array)) sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();

        XmlDocComment.AppendSummary(sb, view.Source.Description, indent: "");
        sb.Append("public partial class ").Append(NameCasing.ToPascalCase(view.Name)).AppendLine(" : IKeyed");
        sb.AppendLine("{");

        foreach (var column in view.Columns)
        {
            var field = column.Field;
            var type = CSharpTypeMapper.PropertyType(field, knownEnumNames, postgres);
            var nullable = field.Nullable ? "?" : string.Empty;
            var initializer = field.Nullable ? string.Empty
                : field.Array ? CSharpTypeMapper.ArrayInitializer
                : CSharpTypeMapper.DefaultInitializer(field.Type!, postgres);
            // [Searchable] — @searchable on a column, with the same meaning as on a model's field: the runtime's $search
            // reads it from the read type, and once a type marks any property only the marked ones are searched.
            if (MddBooster.Core.Ast.FieldAttributes.Has(field, "searchable"))
                sb.AppendLine("    [Searchable]");
            sb.Append("    public ").Append(type).Append(nullable).Append(' ')
              .Append(NameCasing.ToPascalCase(field.Name)).Append(" { get; set; }").AppendLine(initializer);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }
}
