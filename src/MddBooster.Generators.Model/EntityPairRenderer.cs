using System.Globalization;
using System.Text;
using System.Text.Json;
using M3L.Native;
using MddBooster.Core.Generation;
using MddBooster.Core.Semantic;
using MddBooster.Core.Naming;

namespace MddBooster.Generators.Model;

/// <summary>
/// Renders a single M3L entity into the C# read/write entity pair described
/// in the design spec section 3.2: a marker interface <c>IXxx</c>, a write
/// class <c>Xxx : IyuEntity, IXxx</c> mapped to the base table, and a read
/// class <c>XxxExt : IyuEntity, IXxx</c> mapped to the view.
/// </summary>
/// <remarks>
/// The <c>id</c> field (attributed <c>@pk</c>) is elided because
/// <see cref="IyuEntity"/> already provides it. All
/// other stored fields are rendered on both classes and declared in the
/// interface — read-only for the interface contract, get/set for the classes.
/// <para>
/// C16 scope: stored fields only. Lookup/Rollup/Computed fields and enum
/// generation land in C17-C19.
/// </para>
/// </remarks>
public static class EntityPairRenderer
{
    private const string Header = "// <auto-generated> mdd-booster; DO NOT EDIT.</auto-generated>";

    public sealed record RenderedPair(string Interface, string Write, string Read);

    /// <summary>
    /// Which SQL view (if any) backs the Ext read model. Priority:
    /// <c>Ext</c> (user-maintained ExtView) &gt; <c>Full</c> (FullView) &gt;
    /// <c>Ud</c> (UdView) &gt; <c>None</c> (base table).
    /// </summary>
    public enum ExtBacking { None, Ud, Full, Ext }

    /// <param name="oneToOne">
    /// The one-to-one relationships the whole model set declares
    /// (<see cref="OneToOneRelationships.Describe(IReadOnlyList{ResolvedModel})"/>). A model cannot
    /// derive these alone: the navigation on the <em>target</em> side is created by a declaration in
    /// some other model, so the set has to be computed once and handed in. Omitted, the read type
    /// carries no navigation and the output is what it was before this parameter existed.
    /// </param>
    /// <param name="allModels">
    /// Every model being generated — a multi-hop lookup's later keys live on other models, and any
    /// optional key along the path makes the lookup's property optional. Omitted, only the first
    /// hop's key (on this model) is consulted.
    /// </param>
    /// <param name="manyToOne">
    /// The set's many-to-one navigations (<see cref="ManyToOneNavigations.Describe"/>) — computed once
    /// for the set like <paramref name="oneToOne"/>, because which names they may take depends on the
    /// one-to-one navigations around them. Omitted, the read type carries none.
    /// </param>
    /// <param name="collections">
    /// The set's declared reverse collections (<see cref="ReverseCollections.Describe"/>). Omitted, the read type
    /// carries none.
    /// </param>
    public static RenderedPair Render(
        ResolvedModel model,
        string ns,
        IReadOnlySet<string>? knownEnumNames = null,
        ExtBacking extBacking = ExtBacking.None,
        IReadOnlyList<OneToOneRelationships.Relationship>? oneToOne = null,
        IReadOnlyList<ResolvedModel>? allModels = null,
        bool postgres = false,
        IReadOnlyList<ManyToOneNavigations.Navigation>? manyToOne = null,
        IReadOnlyList<ReverseCollections.Collection>? collections = null)
    {
        ArgumentNullException.ThrowIfNull(model);
        ArgumentException.ThrowIfNullOrWhiteSpace(ns);

        var entityName = NameCasing.ToPascalCase(model.Name);

        // PK 지원 게이트 — IyuEntity.Id(Guid 단일 키)와 양립 불가한 모델은 조용히
        // 삼키지 않고 명시적으로 실패한다. (silent drop 금지 — 2026-07-22 이슈)
        var pkFields = model.Fields.Where(f => HasAttribute(f, "pk")).ToList();
        if (pkFields.Count > 1)
        {
            throw new InvalidOperationException(
                $"Model '{model.Name}': 복합 PK({string.Join(", ", pkFields.Select(f => f.Name))})는 " +
                "Model 타깃이 지원하지 않습니다. 단일 identifier PK로 모델링하세요.");
        }
        if (pkFields is [{ } pkField] && pkField.Type != "identifier")
        {
            throw new InvalidOperationException(
                $"Model '{model.Name}.{pkField.Name}': PK 타입 '{pkField.Type}'은 Model 타깃이 지원하지 " +
                "않습니다. 상속되는 IyuEntity.Id(Guid)와 양립하려면 identifier 타입이어야 합니다.");
        }

        // Stored fields (pk + created_at/updated_at elided — inherited from IyuEntity).
        // 비-id PK(공유 PK 확장 테이블)도 elide 대상 — 그 필드는 IyuEntity.Id가 표현하며,
        // EntityConfigurationRenderer가 fluent HasColumnName으로 실제 PK 컬럼에 재매핑한다.
        // Kind.Stored is the default; anything else (Lookup/Rollup/Computed) lives
        // on the Ext read model only.
        var storedFields = model.Fields
            .Where(f => f.Kind == FieldKind.Stored)
            .Where(f => !HasAttribute(f, "pk"))
            .Where(f => !IsInheritedTimestamp(f.Name))
            .ToList();

        var derivedFields = model.Fields
            .Where(f => f.Kind is FieldKind.Lookup or FieldKind.Rollup or FieldKind.Computed)
            .ToList();

        // A field-level @internal field stays on the base table and the write entity
        // (storage), but drops out of the read surface — the interface both classes
        // implement, and the Ext (read) class itself. Dropping it from the interface is
        // not optional: XxxExt still has to compile against IXxx, so IXxx cannot declare
        // a member the Ext class no longer has.
        var readOnlyStoredFields = storedFields.Where(f => !EntitySurface.IsFieldInternal(f)).ToList();
        var readOnlyDerivedFields = derivedFields.Where(f => !EntitySurface.IsFieldInternal(f)).ToList();

        // The external contracts @inherits/@implements name are types this generator cannot see
        // into. The write type carries every stored field, so whatever it claims is the model's
        // claim. The read type can carry the same claim only while it is guaranteed the same
        // members — once a field-level @internal field leaves it, a contract that declares that
        // member would not compile on it, and nothing here can tell whether the contract does.
        // So the read type keeps the contracts exactly as long as it keeps every stored field; a
        // consumer who knows a contract still holds on the narrower type says so in a partial class.
        var readTypeKeepsContracts = readOnlyStoredFields.Count == storedFields.Count;

        var models = allModels ?? [model];
        var nullableLookups = derivedFields
            .Where(f => f.Kind == FieldKind.Lookup && LookupPath.ResultNullable(model, f, models))
            .Select(f => f.Name)
            .ToHashSet(StringComparer.Ordinal);

        return new RenderedPair(
            Interface: RenderInterface(entityName, readOnlyStoredFields, ns, knownEnumNames, postgres, model.Source.Description),
            Write: RenderClass(entityName, storedFields, derivedFields: null, ns, isExt: false, knownEnumNames, extBacking, model.Source, model.Name, oneToOne, manyToOne, nullableLookups, postgres),
            Read: RenderClass(entityName, readOnlyStoredFields, readOnlyDerivedFields, ns, isExt: true, knownEnumNames, extBacking, model.Source, model.Name, oneToOne, manyToOne, nullableLookups, postgres, externalContracts: readTypeKeepsContracts, collections: collections));
    }

    private static string RenderInterface(string entityName, IReadOnlyList<FieldNode> fields, string ns, IReadOnlySet<string>? knownEnumNames, bool postgres, string? description)
    {
        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        // Mapped field types include BCL names (Guid, DateTimeOffset, DateOnly,
        // TimeOnly) that only resolve if the consuming project happens to enable
        // ImplicitUsings. Declaring the dependency here makes the emitted file
        // self-contained instead of silently inheriting the consumer's setting.
        sb.AppendLine("using System;");
        // An array field is a List<T>; the directive is written only where one is, so a model without one renders as
        // it did before arrays were generated.
        if (fields.Any(f => f.Array))
            sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();
        // The model's description — its blockquote or its header's description string — is the documentation
        // a consumer reads on hover, on each of the three types the model becomes.
        XmlDocComment.AppendSummary(sb, description, indent: "");
        sb.Append("public interface I").Append(entityName).AppendLine();
        sb.AppendLine("{");
        sb.AppendLine("    global::System.Guid Id { get; }");
        foreach (var f in fields)
        {
            var cs = CSharpTypeMapper.PropertyType(f, knownEnumNames, postgres);
            var nullable = f.Nullable ? "?" : string.Empty;
            sb.Append("    ").Append(cs).Append(nullable).Append(' ')
              .Append(NameCasing.ToPascalCase(f.Name)).AppendLine(" { get; }");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string RenderClass(
        string entityName,
        IReadOnlyList<FieldNode> storedFields,
        IReadOnlyList<FieldNode>? derivedFields,
        string ns,
        bool isExt,
        IReadOnlySet<string>? knownEnumNames,
        ExtBacking extBacking,
        ModelNode source,
        string modelName,
        IReadOnlyList<OneToOneRelationships.Relationship>? oneToOne,
        IReadOnlyList<ManyToOneNavigations.Navigation>? manyToOne,
        IReadOnlySet<string> nullableLookups,
        bool postgres,
        bool externalContracts = true,
        IReadOnlyList<ReverseCollections.Collection>? collections = null)
    {
        var className = isExt ? entityName + "Ext" : entityName;
        // Ext classes route to the SQL layer that actually exposes their
        // derived columns: {Name}ExtView (rollup/computed), {Name}FullView (lookups
        // only), or the base table (table-only model). Write classes always
        // target the base table.
        var tableName = !isExt
            ? entityName
            : extBacking switch
            {
                ExtBacking.Ext => entityName + "ExtView",
                ExtBacking.Full => entityName + "FullView",
                ExtBacking.Ud => entityName + "UdView",
                _ => entityName,
            };

        // @implements 어트리뷰트에서 추가 인터페이스 추출 (도메인 중립 — 인자는
        // 완전수식명(FQN)을 verbatim 사용, mdd는 global:: 만 접두).
        IEnumerable<FieldAttribute> contractAttributes = externalContracts ? source.Attributes ?? [] : [];
        var extraInterfaces = contractAttributes
            .Where(a => string.Equals(a.Name, "implements", StringComparison.OrdinalIgnoreCase))
            .SelectMany(a => a.Args ?? [])
            .Select(AttributeArgString)
            .Where(s => !string.IsNullOrEmpty(s))
            .Select(iface => $"global::{iface}")
            .ToList();

        // @inherits(FQN) — 기본 베이스클래스 IyuEntity 오버라이드 (도메인 중립).
        // 미지정 시 IyuEntity 유지(하위호환). 단일 인자(C# 단일 상속).
        var inheritsFqn = contractAttributes
            .Where(a => string.Equals(a.Name, "inherits", StringComparison.OrdinalIgnoreCase))
            .SelectMany(a => a.Args ?? [])
            .Select(AttributeArgString)
            .FirstOrDefault(s => !string.IsNullOrEmpty(s));
        var baseClass = string.IsNullOrEmpty(inheritsFqn)
            ? "IyuEntity"
            : $"global::{inheritsFqn}";

        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        // See RenderInterface: mapped field types (Guid/DateTimeOffset/DateOnly/
        // TimeOnly) and DefaultInitializer's Array.Empty<byte>() are BCL names.
        sb.AppendLine("using System;");
        // A reverse collection is an ICollection<T>; the directive is written only where one is, so a model without
        // one renders as it did before collections existed.
        // An array field is a List<T>, under the same rule.
        if ((isExt && (collections ?? []).Any(c => c.CollidesWith is null
                && string.Equals(c.PrincipalModel, modelName, StringComparison.Ordinal)))
            || storedFields.Any(f => f.Array))
            sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.ComponentModel.DataAnnotations;");
        sb.AppendLine("using System.ComponentModel.DataAnnotations.Schema;");
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();
        XmlDocComment.AppendSummary(sb, source.Description, indent: "");
        sb.Append("[Table(").Append(SourceLiteral.CSharpString(tableName)).AppendLine(")]");
        sb.Append("public partial class ").Append(className)
          .Append(" : ").Append(baseClass).Append(", I").Append(entityName);
        foreach (var iface in extraInterfaces)
            sb.Append(", ").Append(iface);
        sb.AppendLine();
        sb.AppendLine("{");
        // The keys this class follows with a navigation — where a key's @searchable lands instead of
        // on the key (SearchableReferences). The write type navigates every navigable key; the read
        // type only those whose navigation is emitted.
        var navigatedKeys = isExt
            ? SearchableReferences.ReadNavigatedKeys(modelName, oneToOne, manyToOne)
            : storedFields.Where(f => HasWriteNavigation(source, f)).Select(f => f.Name).ToHashSet(StringComparer.Ordinal);
        var searchableKeys = storedFields
            .Where(SearchableReferences.IsSearchableReference)
            .Select(f => f.Name)
            .Where(navigatedKeys.Contains)
            .ToHashSet(StringComparer.Ordinal);
        foreach (var f in storedFields)
        {
            RenderProperty(sb, source, f, knownEnumNames, nullableLookups, isExt, postgres, searchableKeys);
        }
        if (derivedFields is { Count: > 0 })
        {
            foreach (var f in derivedFields)
            {
                RenderProperty(sb, source, f, knownEnumNames, nullableLookups, isExt, postgres, searchableKeys);
            }
        }
        if (isExt) RenderOneToOneNavigation(sb, modelName, oneToOne, searchableKeys);
        if (isExt) RenderManyToOneNavigation(sb, modelName, manyToOne, searchableKeys);
        if (isExt) RenderCollections(sb, modelName, collections);
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// The declared reverse collections on a read type (<see cref="ReverseCollections.Describe"/>): the dependents'
    /// read types whose key points at this row. A collection marked as colliding is not emitted.
    /// </summary>
    private static void RenderCollections(
        StringBuilder sb, string modelName, IReadOnlyList<ReverseCollections.Collection>? collections)
    {
        foreach (var c in collections ?? [])
        {
            if (c.CollidesWith is not null) continue;
            if (!string.Equals(c.PrincipalModel, modelName, StringComparison.Ordinal)) continue;
            sb.AppendLine();
            sb.Append("    public ICollection<").Append(NameCasing.ToPascalCase(c.DependentModel)).Append("Ext> ")
              .Append(c.Name).AppendLine(" { get; set; } = [];");
        }
    }

    /// <summary>
    /// The one-to-one navigation pair on a read type: the reference to the target, and on the target
    /// the reference back.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Both halves, always, and that is the point rather than thoroughness — EF infers the
    /// multiplicity from a <em>reciprocal</em> pair of reference navigations, so a single side would
    /// leave the relationship a many-to-one and quietly wrong. Measured in the runtime library
    /// against two view-mapped types, which is what these read types are.
    /// </para>
    /// <para>
    /// The forward side follows the key's optionality: a required foreign key cannot point at a
    /// missing row. The reverse side is always optional, because a target row exists whether or not
    /// anything points at it.
    /// </para>
    /// <para>
    /// Names are not derived here. They come from the model set alongside the relationship, where
    /// they are checked for collisions — a reverse name shared by two references to one target fails
    /// the build rather than letting one navigation win, and such a relationship is skipped here so
    /// this method never emits the duplicate that would result.
    /// </para>
    /// </remarks>
    private static void RenderOneToOneNavigation(
        StringBuilder sb, string modelName, IReadOnlyList<OneToOneRelationships.Relationship>? oneToOne,
        IReadOnlySet<string> searchableKeys)
    {
        if (oneToOne is null || oneToOne.Count == 0) return;

        foreach (var r in oneToOne)
        {
            if (r.ReverseNameConflict is not null) continue;

            if (string.Equals(r.DependentModel, modelName, StringComparison.Ordinal))
            {
                var target = NameCasing.ToPascalCase(r.TargetModel) + "Ext";
                sb.AppendLine();
                if (searchableKeys.Contains(r.ForeignKeyField))
                    sb.AppendLine("    [Searchable]");
                if (r.IsOptional)
                    sb.Append("    public ").Append(target).Append("? ").Append(r.ForwardName)
                      .AppendLine(" { get; set; }");
                else
                    sb.Append("    public ").Append(target).Append(' ').Append(r.ForwardName)
                      .AppendLine(" { get; set; } = null!;");
            }

            if (r.HasInverse && string.Equals(r.TargetModel, modelName, StringComparison.Ordinal))
            {
                var dependent = NameCasing.ToPascalCase(r.DependentModel) + "Ext";
                sb.AppendLine();
                sb.Append("    public ").Append(dependent).Append("? ").Append(r.ReverseName)
                  .AppendLine(" { get; set; }");
            }
        }
    }

    /// <summary>
    /// The many-to-one navigations on a read type: one per ordinary reference key, pointing at the
    /// target's read type. Nullability follows the key, as on the forward side of a one-to-one.
    /// </summary>
    /// <remarks>
    /// Names come from <see cref="ManyToOneNavigations.Describe"/>, which also decides that a name
    /// already taken on this read type loses — a navigation marked as colliding is not emitted, so the
    /// class always compiles and the analyzer says what was left out.
    /// </remarks>
    private static void RenderManyToOneNavigation(
        StringBuilder sb, string modelName, IReadOnlyList<ManyToOneNavigations.Navigation>? manyToOne,
        IReadOnlySet<string> searchableKeys)
    {
        if (manyToOne is null || manyToOne.Count == 0) return;

        foreach (var n in manyToOne)
        {
            if (n.CollidesWith is not null) continue;
            if (!string.Equals(n.DependentModel, modelName, StringComparison.Ordinal)) continue;

            var target = NameCasing.ToPascalCase(n.TargetModel) + "Ext";
            sb.AppendLine();
            if (searchableKeys.Contains(n.ForeignKeyField))
                sb.AppendLine("    [Searchable]");
            if (n.IsOptional)
                sb.Append("    public ").Append(target).Append("? ").Append(n.Name)
                  .AppendLine(" { get; set; }");
            else
                sb.Append("    public ").Append(target).Append(' ').Append(n.Name)
                  .AppendLine(" { get; set; } = null!;");
        }
    }

    private static void RenderProperty(
        StringBuilder sb,
        ModelNode owner,
        FieldNode f,
        IReadOnlySet<string>? knownEnumNames,
        IReadOnlySet<string>? nullableLookups,
        bool isExt,
        bool postgres,
        IReadOnlySet<string> searchableKeys)
    {
        var cs = CSharpTypeMapper.PropertyType(f, knownEnumNames, postgres);

        // A lookup read through an optional key at any hop yields NULL whenever that key is NULL
        // (each hop is a LEFT JOIN) — LookupPath.ResultNullable decided which, for the whole path.
        var effectiveNullable = f.Nullable
            || (f.Kind == FieldKind.Lookup && nullableLookups is not null && nullableLookups.Contains(f.Name));

        var nullable = effectiveNullable ? "?" : string.Empty;
        var prop = NameCasing.ToPascalCase(f.Name);

        var isEnumField = knownEnumNames is not null && knownEnumNames.Contains(f.Type!);

        // A declared default (`= value`) is the property's initializer when the
        // field has one. Without this the CLR default is stored silently: EF
        // writes the zero value explicitly, so the column's DDL DEFAULT never
        // gets the chance to fire and `boolean = true` lands as false.
        // Nullable fields are excluded on purpose — seeding an optional property
        // changes what "unset" means, which is a separate trade-off.
        var declaredInitializer = !effectiveNullable && f.Kind == FieldKind.Stored
            ? DeclaredDefaultInitializer(f, knownEnumNames)
            : null;

        // Otherwise: nullable reference/value types default to null — no
        // initializer needed. Non-nullable types: non-null reference types get an
        // explicit default (for nullable-reference analysis); value types
        // (including enums) auto-default to 0/false.
        // An array declares no default (MDD048 refuses one); a non-nullable one starts as an empty list.
        var initializer = f.Array
            ? (effectiveNullable ? string.Empty : CSharpTypeMapper.ArrayInitializer)
            : declaredInitializer
                ?? (effectiveNullable || isEnumField
                    ? string.Empty
                    : CSharpTypeMapper.DefaultInitializer(f.Type!, postgres));

        // [Column(TypeName = "decimal(p,s)")] for decimal fields with explicit precision.
        // Suppresses EF Core's "No store type specified" warning and aligns the CLR
        // mapping with the SQL DECIMAL(p,s) column the SQL generator emits. Not on an
        // array of decimals: its column is the list's (JSON text or a native array),
        // not one decimal's, and the digits describe each element.
        if (f.Type == "decimal" && !f.Array)
        {
            var decParams = MddBooster.Core.Ast.FieldAttributes.TypeParams(f);
            if (decParams is { Count: >= 1 })
            {
                var scale = decParams.Count >= 2 ? decParams[1] : "0";
                sb.Append("    [Column(TypeName = \"decimal(")
                  .Append(decParams[0]).Append(',').Append(scale)
                  .AppendLine(")\")]");
            }
        }

        // Emit [Reference("Target")] for foreign-key properties.
        var referenceTarget = GetAttributeFirstParam(f, "reference");
        if (!string.IsNullOrEmpty(referenceTarget))
        {
            sb.Append("    [Reference(").Append(SourceLiteral.CSharpString(referenceTarget)).AppendLine(")]");
        }

        // [Binding("Entity", "Column")] — # Entity.Column 바인딩
        if (f.Binding is not null)
        {
            sb.Append("    [Binding(").Append(SourceLiteral.CSharpString(f.Binding.Entity)).Append(", ")
              .Append(SourceLiteral.CSharpString(f.Binding.Column)).AppendLine(")]");
        }

        // Derived-field markers: [Lookup], [Rollup], [Computed].
        // The SQL view populates these; EF never writes them back.
        switch (f.Kind)
        {
            case FieldKind.Lookup:
                var lookupArg = GetAttributeFirstParam(f, "lookup")
                    ?? f.Lookup?.Path
                    ?? string.Empty;
                sb.Append("    [Lookup(")
                  .Append(SourceLiteral.CSharpString(lookupArg)).AppendLine(")]");
                break;
            case FieldKind.Rollup:
                var rollupExpr = GetRollupExpression(f);
                sb.Append("    [Rollup(")
                  .Append(SourceLiteral.CSharpString(rollupExpr));
                if (HasAttribute(f, "indexed"))
                    sb.Append(", Indexed = true");
                sb.AppendLine(")]");
                break;
            case FieldKind.Computed:
                // The metadata carries the expression this dialect's views use: the one declared for its platform,
                // otherwise the portable one (as written — translation is the SQL target's).
                var computedExpr = ExpressionSelection.Select(f.Computed, postgres ? SqlDialect.PostgreSql : SqlDialect.SqlServer)?.Text
                    ?? GetAttributeFirstParam(f, "computed")
                    ?? string.Empty;
                // Strip surrounding backticks that M3L uses to fence expressions
                if (computedExpr.Length >= 2 && computedExpr.StartsWith('`') && computedExpr.EndsWith('`'))
                    computedExpr = computedExpr[1..^1];
                sb.Append("    [Computed(")
                  .Append(SourceLiteral.CSharpString(computedExpr)).AppendLine(")]");
                break;
        }

        // Validation attributes — the constraints the model already declares,
        // carried to the C# entity so the API surface enforces them instead of
        // letting a violation reach the database and come back as a raw provider
        // error. They read the same sources the SQL column does — field
        // nullability, and the field's effective length bound — so the two
        // targets cannot drift.
        //
        // Stored fields only: Lookup/Rollup/Computed properties are populated by
        // the view and a caller never supplies them. `[Required]` on one would
        // reject every create request, because a non-nullable derived string
        // carries the `string.Empty` initializer that RequiredAttribute rejects.
        if (f.Kind == FieldKind.Stored)
        {
            // [Required] — non-nullable reference types only. Nullability comes
            // from the parsed flag, not from the `@not_null` attribute: a plain
            // `- name: string(50)` is already non-nullable, and the SQL column's
            // NOT NULL is derived the same way.
            // An array's property is a List<T> — a reference type whatever its element is.
            if (!f.Nullable && (f.Array || CSharpTypeMapper.IsReferenceType(f.Type!)))
                sb.AppendLine("    [Required]");

            // [StringLength(n)] — the bound the field actually carries, which is
            // the number the SQL column is sized with. A bound can be written
            // down (`string(50)`) or implied by the type (`email`); reading only
            // the written one is how a column came to be narrower than the
            // attribute guarding writes to it. Independent of nullability: an
            // optional `string(50)?` is still bounded at 50.
            if (MddBooster.Core.Ast.FieldAttributes.EffectiveMaxLength(f) is { } maxLength)
                sb.Append("    [StringLength(").Append(maxLength).AppendLine(")]");

            // [Range(min, max)] — the numeric bounds the model declares, which until now
            // reached the generated TypeScript field schema and stopped there: the same
            // declaration was honoured in one artifact and silently absent from the other.
            // Numeric types only — @min/@max are read as numbers (FieldAttributes.Number, the
            // same reader the TypeScript schema uses), and a string's bound is already carried
            // by [StringLength] above.
            //
            // A one-sided declaration still emits both ends, because RangeAttribute has no
            // open-ended form: the undeclared side becomes the widest value the CLR type can
            // hold, which constrains nothing it did not already constrain.
            if (RangeBounds(f) is { } range)
                sb.Append("    [Range(").Append(range.Min).Append(", ").Append(range.Max).AppendLine(")]");

            // [DecimalDigits(p, s)] — a decimal's digits, the way [StringLength] carries a string's bound: the column
            // keeps exactly these, and without the rule in front of it a value with more decimal places was stored
            // rounded (the caller reads back a number it never sent) and one with more integer digits failed the write.
            // The same digits the SQL column is declared with, bare decimal included. Not on an array of decimals: the
            // attribute validates one decimal value, and a list is not one.
            if (f.Type == "decimal" && !f.Array)
            {
                var (precision, scale) = MddBooster.Core.Types.M3lPrimitives.DecimalDigitsOf(
                    MddBooster.Core.Ast.FieldAttributes.TypeParams(f));
                sb.Append("    [DecimalDigits(").Append(precision).Append(", ").Append(scale).AppendLine(")]");
            }

            // [Editable] — who may supply the value, as metadata. @system: nobody outside the
            // application's own code, at creation or after. @immutable: a caller supplies it once, at
            // creation, which is what AllowInitialValue says — without it the two declarations would
            // read the same. Metadata only, like [Required]/[StringLength] above; the enforced half of
            // @system is the Api target's write exclusion, and @immutable has none.
            if (FieldAuthorship.IsDeclaredSystem(f))
                sb.AppendLine("    [Editable(false)]");
            else if (MddBooster.Core.Ast.FieldAttributes.Has(f, "immutable"))
                sb.AppendLine("    [Editable(false, AllowInitialValue = true)]");

            // [Timestamp] — the row version. On both classes, for two different readers: EF takes
            // the write type's as a concurrency token the engine generates (so an update with a
            // stale version affects no row), and the OData model builder takes the read type's as
            // the ETag source. The runtime keeps a concurrency token out of every write body.
            if (MddBooster.Core.Types.M3lPrimitives.IsRowVersion(f))
                sb.AppendLine("    [Timestamp]");
        }

        // [Searchable] — @searchable, the fields free-text search is meant for. The runtime's $search
        // reads it from the read type: once a type marks any property, only the marked ones are
        // searched. Emitted on both classes so the declaration does not depend on which one a
        // consumer's own search code reflects over. A reference key this class navigates carries it
        // on the navigation instead (SearchableReferences) — a key is not text.
        if (MddBooster.Core.Ast.FieldAttributes.Has(f, "searchable") && !searchableKeys.Contains(f.Name))
            sb.AppendLine("    [Searchable]");

        // [Display(Name, GroupName, Description)] — field label/group/help from M3L declaration.
        // The authored label (FieldAttributes.DisplayLabel); unlike FieldAttributes.EffectiveLabel this
        // does NOT fall back to the PascalCase field name — presence of Name here signals
        // authored, meaningful text (No_Display_when_field_has_no_label_or_group pins the
        // alternative: omit [Display] entirely rather than restate the property's own name).
        // @help(text) maps to Description — the same free-text field TsFormRenderer's helpText
        // already reads, so this mirrors an existing, established mapping rather than inventing one.
        var displayLabel = MddBooster.Core.Ast.FieldAttributes.DisplayLabel(f);
        var displayGroup = MddBooster.Core.Ast.FieldAttributes.EffectiveGroup(f);
        var displayHelp = GetAttributeString(f, "help");
        if (displayLabel != null || displayGroup != null || displayHelp != null)
        {
            sb.Append("    [Display(");
            var displayParts = new List<string>();
            if (displayLabel != null) displayParts.Add($"Name = {SourceLiteral.CSharpString(displayLabel)}");
            if (displayGroup != null) displayParts.Add($"GroupName = {SourceLiteral.CSharpString(displayGroup)}");
            if (displayHelp != null) displayParts.Add($"Description = {SourceLiteral.CSharpString(displayHelp)}");
            sb.Append(string.Join(", ", displayParts));
            sb.AppendLine(")]");
        }

        sb.Append("    public ").Append(cs).Append(nullable).Append(' ')
          .Append(prop).Append(" { get; set; }").AppendLine(initializer);

        // Write entity only: emit EF Core navigation property for [Reference] FK fields
        // whose navigation has a name — declared in ### Relations, or the key's xxx_id stem.
        // EF Core uses nav properties to infer INSERT order; without them, bulk
        // SaveChanges calls with parent+child in the same batch produce FK violations.
        if (!isExt && HasWriteNavigation(owner, f))
        {
            var navName = ManyToOneNavigations.NavigationName(owner, f)!;
            if (searchableKeys.Contains(f.Name))
                sb.AppendLine("    [Searchable]");
            if (effectiveNullable)
                sb.Append("    public ").Append(referenceTarget).Append("? ")
                  .Append(navName).AppendLine(" { get; set; }");
            else
                sb.Append("    public ").Append(referenceTarget).Append(" ")
                  .Append(navName).AppendLine(" { get; set; } = null!;");
        }
    }

    /// <summary>
    /// Whether the write entity carries a reference navigation for this field — a <c>@reference</c> key whose
    /// navigation has a name (<see cref="ManyToOneNavigations.NavigationName"/>). <see cref="EntityConfigurationRenderer"/>
    /// configures the relationship through that navigation, so both read the same rule.
    /// </summary>
    internal static bool HasWriteNavigation(ModelNode owner, FieldNode f) => ManyToOneNavigations.IsNavigableKey(owner, f);

    /// <summary>
    /// Turns a declared default (<c>= value</c>, or the <c>@default(value)</c>
    /// spelling) into a C# property initializer, or <c>null</c> when the default
    /// cannot be expressed as a literal.
    /// </summary>
    /// <remarks>
    /// The gate is the <em>target type</em>, not the shape of the default text.
    /// Only types with a C# literal form are emitted; temporals,
    /// <c>identifier</c> and <c>binary</c> are skipped whatever their default
    /// says. Server-side defaults such as <c>now()</c> therefore fall out as a
    /// consequence rather than as named exceptions — a list of function names
    /// would let the next one through and emit code that does not compile.
    /// </remarks>
    private static string? DeclaredDefaultInitializer(FieldNode f, IReadOnlySet<string>? knownEnumNames)
    {
        var raw = MddBooster.Core.Ast.FieldAttributes.EffectiveDefault(f);
        if (string.IsNullOrEmpty(raw)) return null;

        var type = f.Type!;

        // Enum defaults arrive as the bare snake_case member name (the parser
        // strips the quotes). The member expression has to use the same
        // PascalCase conversion EnumRenderer applies, or it names a member that
        // was never generated.
        if (knownEnumNames is not null && knownEnumNames.Contains(type))
            return $" = {NameCasing.ToPascalCase(type)}.{NameCasing.ToPascalCase(raw)};";

        return type switch
        {
            "boolean" => raw is "true" or "false" ? $" = {raw};" : null,
            "integer" or "long" or "short" or "byte" => IsIntegerLiteral(raw) ? $" = {raw};" : null,
            // An unsuffixed literal is a double: assigning it to float or decimal
            // is CS0664, so both need their suffix.
            "float" => IsNumericLiteral(raw) ? $" = {raw}f;" : null,
            "double" => IsNumericLiteral(raw) ? $" = {raw};" : null,
            "decimal" => IsNumericLiteral(raw) ? $" = {raw}m;" : null,
            "string" or "text" or "json" or "phone" or "email" or "url"
                => $" = {SourceLiteral.CSharpString(raw)};",
            // date/time/timestamp/datetime/identifier/binary have no literal form.
            _ => null,
        };
    }

    private static bool IsIntegerLiteral(string s) =>
        long.TryParse(s, System.Globalization.NumberStyles.Integer,
            System.Globalization.CultureInfo.InvariantCulture, out _);

    private static bool IsNumericLiteral(string s) =>
        double.TryParse(s, System.Globalization.NumberStyles.Float,
            System.Globalization.CultureInfo.InvariantCulture, out _);

    private static string GetRollupExpression(FieldNode f)
    {
        // Prefer the structured RollupDef when present; fall back to joining
        // attribute args so hand-written fixtures without the parsed block
        // still round-trip.
        if (f.Rollup is not null)
        {
            var fkPart = string.IsNullOrEmpty(f.Rollup.Fk) ? f.Rollup.Target : $"{f.Rollup.Target}.{f.Rollup.Fk}";
            return string.IsNullOrEmpty(f.Rollup.Aggregate) ? fkPart : $"{fkPart}:{f.Rollup.Aggregate}";
        }
        var attr = MddBooster.Core.Ast.FieldAttributes.Find(f, "rollup");
        if (attr?.Args is { Count: > 0 })
        {
            return string.Join(":", attr.Args.Select(a =>
                a.ValueKind == System.Text.Json.JsonValueKind.String ? a.GetString() : a.GetRawText()));
        }
        return string.Empty;
    }

    private static string? GetAttributeFirstParam(FieldNode field, string name)
    {
        var attr = MddBooster.Core.Ast.FieldAttributes.Find(field, name);
        if (attr?.Args is null || attr.Args.Count == 0) return null;
        var first = attr.Args[0];
        return first.ValueKind == System.Text.Json.JsonValueKind.String
            ? first.GetString()
            : first.GetRawText();
    }

    private static string? GetAttributeString(FieldNode field, string attrName)
    {
        var attr = MddBooster.Core.Ast.FieldAttributes.Find(field, attrName);
        if (attr?.Args is { Count: > 0 }
            && attr.Args[0].ValueKind == System.Text.Json.JsonValueKind.String)
        {
            return attr.Args[0].GetString();
        }
        return null;
    }

    /// <summary>
    /// Extracts a model-attribute argument as a plain string, unwrapping JSON
    /// string values and stripping quotes from raw tokens. Used by the
    /// domain-neutral <c>@implements</c>/<c>@inherits</c> knobs where the
    /// argument is a verbatim fully-qualified type name.
    /// </summary>
    private static string AttributeArgString(JsonElement arg) =>
        arg.ValueKind == JsonValueKind.String
            ? arg.GetString()!
            : arg.GetRawText().Trim('"');

    private static bool HasAttribute(FieldNode field, string name) =>
        MddBooster.Core.Ast.FieldAttributes.Has(field, name);

    private static bool IsInheritedTimestamp(string fieldName) =>
        string.Equals(fieldName, "created_at", StringComparison.OrdinalIgnoreCase)
        || string.Equals(fieldName, "updated_at", StringComparison.OrdinalIgnoreCase);


    /// <summary>
    /// The `[Range]` ends for a field that declares `@min` and/or `@max`, or null when the
    /// declaration does not apply — a non-numeric field, or neither bound declared.
    /// </summary>
    /// <remarks>
    /// The open side is the CLR type's own limit written as a C# constant, so the emitted
    /// attribute stays readable and exact rather than repeating a magic number. `decimal` and
    /// the 64-bit types take `double` limits: RangeAttribute's numeric constructor is
    /// `(double, double)`, and `decimal.MaxValue` has no implicit conversion to it.
    /// </remarks>
    private static (string Min, string Max)? RangeBounds(FieldNode f)
    {
        var min = MddBooster.Core.Ast.FieldAttributes.Number(f, "min");
        var max = MddBooster.Core.Ast.FieldAttributes.Number(f, "max");
        if (min is null && max is null) return null;

        (string Lower, string Upper)? limits = f.Type switch
        {
            "byte" or "short" or "integer" => ("int.MinValue", "int.MaxValue"),
            "long" or "float" or "double" or "decimal" => ("double.MinValue", "double.MaxValue"),
            _ => null,
        };
        if (limits is not { } clrLimits) return null;

        return (Literal(min) ?? clrLimits.Lower, Literal(max) ?? clrLimits.Upper);

        static string? Literal(double? value) => value?.ToString("R", CultureInfo.InvariantCulture);
    }
