using System.Text;
using M3L.Native;
using MddBooster.Core.Generation;
using MddBooster.Core.Naming;

namespace MddBooster.Generators.Model;

/// <summary>
/// Renders an M3L top-level enum declaration (<c>## Name ::enum</c>) into a
/// C# enum type with <c>[EnumMember]</c> attributes that carry the original
/// snake_case value names. The snake_case form is what EF Core persists via
/// <c>HasConversion&lt;string&gt;()</c> — and, when the SQL target's opt-in
/// <c>EmitEnumCheckConstraints</c> knob is on, what the generated CHECK
/// constraint enforces (see <c>EnumSqlConvention</c> in the SQL generator).
/// DB-level enforcement is otherwise absent by design (SSDT dacpac CHECK diff
/// instability); EF-level conversion is then the only guard.
/// </summary>
/// <remarks>
/// <para>
/// M3L enum members use snake_case (<c>in_production</c>); the generated C#
/// member is PascalCase (<c>InProduction</c>) with an explicit
/// <c>[EnumMember(Value = "in_production")]</c> attribute so that JSON
/// serialization and the string value converter both round-trip through the
/// M3L name.
/// </para>
/// <para>
/// The enum's XML doc comment carries the M3L enum description (if any) and
/// each member's doc comment carries the value label for tooling surfaces
/// (IntelliSense, GraphQL schema docs). The same label is also emitted as
/// <c>[Display(Name = "…")]</c> so it can be read at run time — a doc comment
/// is compiled away, and a host that renders a document server-side (a report,
/// an export, a mail body) has no way back to the declared text. The
/// TypeScript target has carried that text in a runtime map since its label
/// map existed; this is the C# half of the same declaration.
/// </para>
/// </remarks>
public static class EnumRenderer
{
    private const string Header = "// <auto-generated> mdd-booster; DO NOT EDIT.</auto-generated>";

    public static string Render(EnumNode enumNode, string ns)
    {
        ArgumentNullException.ThrowIfNull(enumNode);
        ArgumentException.ThrowIfNullOrWhiteSpace(ns);

        var typeName = NameCasing.ToPascalCase(enumNode.Name);
        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System.ComponentModel.DataAnnotations;");
        sb.AppendLine("using System.Runtime.Serialization;");
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();

        XmlDocComment.AppendSummary(sb, enumNode.Description, indent: "");

        sb.Append("public enum ").AppendLine(typeName);
        sb.AppendLine("{");

        for (var i = 0; i < enumNode.Values.Count; i++)
        {
            var v = enumNode.Values[i];
            var memberName = NameCasing.ToPascalCase(v.Name);

            XmlDocComment.AppendSummary(sb, v.Description, indent: "    ");
            // [Display(Name)] — the declared label, readable at run time.
            // Omitted when the member declares no label, matching the field path's rule
            // (EntityPairRenderer's No_Display_when_field_has_no_label_or_group): the
            // presence of Name means authored text, not a restatement of the member's own
            // name. A reader falls back to the member name itself, the way
            // DisplayAttribute consumers already do. The TypeScript label map takes the
            // opposite default, and has to — a Record<T, string> must be total.
            if (!string.IsNullOrWhiteSpace(v.Description))
                sb.Append("    [Display(Name = ").Append(SourceLiteral.CSharpString(v.Description!)).AppendLine(")]");

            sb.Append("    [EnumMember(Value = ").Append(SourceLiteral.CSharpString(v.Name ?? string.Empty)).AppendLine(")]");
            sb.Append("    ").Append(memberName);
            sb.AppendLine(i < enumNode.Values.Count - 1 ? "," : string.Empty);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

}
