using System.Text;
using MddBooster.Core.Ast;
using MddBooster.Core.Naming;
using MddBooster.Core.Semantic;

namespace MddBooster.Generators.Model;

/// <summary>
/// Renders a partial <c>{Name}DbContext</c> class that inherits from
/// <c>IyuDbContext</c>, exposes a <c>DbSet&lt;T&gt;</c> and
/// <c>DbSet&lt;TExt&gt;</c> for every entity in the input model collection,
/// and applies each entity type's configuration (<see cref="EntityConfigurationRenderer"/>).
/// </summary>
/// <remarks>
/// The configurations are applied by name, one call each, in <see cref="EntityConfigurationRenderer.ConfiguredTypes"/>
/// order — not discovered by scanning an assembly. The context names exactly the types it serves, and a configuration
/// missing from the assemblies it compiles against is a build error rather than a mapping silently left out.
/// <para>
/// One statement of storage is the context's rather than a configuration's: on the SQL Server dialect a list field's
/// column type, which only holds on SQL Server and so needs the provider the context knows and a configuration does
/// not (<see cref="EntityConfigurationRenderer.JsonTextListColumns"/>). It covers referenced types too — the context
/// serves them, and their configurations, generated elsewhere, stay provider-neutral like this build's.
/// </para>
/// </remarks>
public static class DbContextRenderer
{
    private const string Header = "// <auto-generated> mdd-booster; DO NOT EDIT.</auto-generated>";

    /// <summary>
    /// One <c>DbSet</c> property of the context: the entity type, the property's name, and whether it is the read half
    /// of the model set just before it.
    /// </summary>
    public sealed record ContextSet(string EntityType, string PropertyName, bool ReadHalf = false);

    /// <summary>
    /// The sets the context exposes for <paramref name="models"/> and <paramref name="readViews"/>, in the context's
    /// order — a model's write and read type, a view's read type. 🔴 The one home of their names: a data interface
    /// (<see cref="DataInterfaceRenderer"/>) declares the same properties, and a name that differed would leave the
    /// context not implementing it.
    /// </summary>
    public static IEnumerable<ContextSet> Sets(IEnumerable<ResolvedModel> models, IEnumerable<ResolvedView>? readViews = null)
    {
        foreach (var model in models.OrderBy(m => m.Name, StringComparer.Ordinal))
        {
            var name = NameCasing.ToPascalCase(model.Name);
            var plural = Pluralizer.Pluralize(name);
            yield return new ContextSet(name, plural);
            yield return new ContextSet(name + "Ext", plural + "Ext", ReadHalf: true);
        }
        foreach (var view in (readViews ?? []).OrderBy(v => v.Name, StringComparer.Ordinal))
        {
            var name = NameCasing.ToPascalCase(view.Name);
            yield return new ContextSet(name, Pluralizer.Pluralize(name));
        }
    }

    /// <param name="implements">The data interface the context implements (the topmost layer's), if any.</param>
    public static string Render(
        IReadOnlyList<ResolvedModel> models,
        string contextName,
        string ns,
        IReadOnlyList<ResolvedView>? readViews = null,
        bool sqlServer = true,
        string? implements = null)
    {
        ArgumentNullException.ThrowIfNull(models);
        ArgumentException.ThrowIfNullOrWhiteSpace(contextName);
        ArgumentException.ThrowIfNullOrWhiteSpace(ns);

        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using Microsoft.EntityFrameworkCore;");
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();
        sb.Append("public partial class ").Append(contextName)
          .Append(" : IyuDbContext");
        if (implements is not null) sb.Append(", ").Append(implements);
        sb.AppendLine();
        sb.AppendLine("{");
        sb.Append("    public ").Append(contextName)
          .Append("(DbContextOptions<").Append(contextName).AppendLine("> options)");
        sb.AppendLine("        : base(options) { }");

        // A model's write and read set together; a standalone view served as a read model has one set, no write half.
        foreach (var set in Sets(models, readViews))
        {
            if (!set.ReadHalf) sb.AppendLine();
            sb.Append("    public DbSet<").Append(set.EntityType).Append("> ")
              .Append(set.PropertyName).Append(" => Set<").Append(set.EntityType).AppendLine(">();");
        }

        sb.AppendLine();
        sb.AppendLine("    protected override void OnModelCreating(ModelBuilder modelBuilder)");
        sb.AppendLine("    {");
        sb.AppendLine("        base.OnModelCreating(modelBuilder);");
        foreach (var type in EntityConfigurationRenderer.ConfiguredTypes(models, readViews))
        {
            sb.Append("        modelBuilder.ApplyConfiguration(new ")
              .Append(EntityConfiguration.ConfigurationClassName(type)).AppendLine("());");
        }
        var listColumns = sqlServer ? EntityConfigurationRenderer.JsonTextListColumns(models, readViews) : [];
        if (listColumns.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("        // A list field's column is JSON text, NVARCHAR(MAX). SQL Server's provider picks the json type for a list from");
            sb.AppendLine("        // compatibility level 170, and the text column refuses its writes; another provider keeps its own storage.");
            sb.AppendLine("        if (Database.ProviderName == \"Microsoft.EntityFrameworkCore.SqlServer\")");
            sb.AppendLine("        {");
            foreach (var (type, property) in listColumns)
            {
                sb.Append("            modelBuilder.Entity<").Append(type).Append(">().Property(e => e.").Append(property)
                  .AppendLine(").HasColumnType(\"nvarchar(max)\");");
            }
            sb.AppendLine("        }");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }
}
