using System.Text;

namespace MddBooster.Generators.Model;

/// <summary>
/// Renders a layer's data interface: the sets of that layer's types, and — on the lowest declared one — the part of the
/// context's own surface a data service uses. The generated context implements the topmost one, and each extends the
/// one below it, so code in a layer receives the context as its own layer's interface and compiles against that layer
/// and the layers beneath it only.
/// </summary>
/// <remarks>
/// <para>
/// Every member is one <c>DbContext</c> (or the generated context) already declares with that exact signature, so the
/// context implements the interfaces implicitly — nothing is forwarded, and the instance a layer receives is the
/// context itself (one change tracker, one transaction).
/// </para>
/// <para>
/// The context surface is what a data service reaches for besides a typed set: <c>Set&lt;T&gt;()</c> for a type the
/// interface does not name, <c>Database</c> (transactions, raw SQL), <c>ChangeTracker</c>, <c>Entry</c>, adding and
/// removing, and saving. Anything else of <c>DbContext</c> is reached through those.
/// </para>
/// </remarks>
public static class DataInterfaceRenderer
{
    private const string Header = "// <auto-generated> mdd-booster; DO NOT EDIT.</auto-generated>";

    /// <param name="name">The interface's name.</param>
    /// <param name="ns">The namespace it is rendered in (placement moves it into its module's).</param>
    /// <param name="sets">The sets of the types this layer adds.</param>
    /// <param name="extends">The interface of the layer beneath, or <see langword="null"/> for the lowest — which then carries the context surface.</param>
    public static string Render(string name, string ns, IReadOnlyList<DbContextRenderer.ContextSet> sets, string? extends)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(name);
        ArgumentException.ThrowIfNullOrWhiteSpace(ns);
        ArgumentNullException.ThrowIfNull(sets);

        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using Microsoft.EntityFrameworkCore;");
        if (extends is null)
        {
            sb.AppendLine("using Microsoft.EntityFrameworkCore.ChangeTracking;");
            sb.AppendLine("using Microsoft.EntityFrameworkCore.Infrastructure;");
        }
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine(extends is null
            ? "/// The data of this layer, as the generated context serves it — its sets and the context's own surface."
            : "/// The data of this layer and the layers beneath it, as the generated context serves it.");
        sb.AppendLine("/// </summary>");
        sb.Append("public interface ").Append(name);
        if (extends is not null) sb.Append(" : ").Append(extends);
        sb.AppendLine();
        sb.AppendLine("{");

        if (extends is null)
        {
            foreach (var member in ContextSurface) sb.Append("    ").AppendLine(member);
            if (sets.Count > 0) sb.AppendLine();
        }
        foreach (var set in sets)
            sb.Append("    DbSet<").Append(set.EntityType).Append("> ").Append(set.PropertyName).AppendLine(" { get; }");

        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>The context members the lowest interface declares — each exactly as <c>DbContext</c> declares it.</summary>
    private static readonly string[] ContextSurface =
    [
        "DbSet<TEntity> Set<TEntity>() where TEntity : class;",
        "DatabaseFacade Database { get; }",
        "ChangeTracker ChangeTracker { get; }",
        "EntityEntry<TEntity> Entry<TEntity>(TEntity entity) where TEntity : class;",
        "EntityEntry Entry(object entity);",
        "EntityEntry<TEntity> Add<TEntity>(TEntity entity) where TEntity : class;",
        "void AddRange(params object[] entities);",
        "void AddRange(global::System.Collections.Generic.IEnumerable<object> entities);",
        "EntityEntry<TEntity> Remove<TEntity>(TEntity entity) where TEntity : class;",
        "void RemoveRange(params object[] entities);",
        "void RemoveRange(global::System.Collections.Generic.IEnumerable<object> entities);",
        "int SaveChanges();",
        "int SaveChanges(bool acceptAllChangesOnSuccess);",
        "global::System.Threading.Tasks.Task<int> SaveChangesAsync(global::System.Threading.CancellationToken cancellationToken = default);",
        "global::System.Threading.Tasks.Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, global::System.Threading.CancellationToken cancellationToken = default);",
    ];
}
