using System.Text.RegularExpressions;
using MddBooster.Core.Naming;

namespace MddBooster.Generators.Sql;

/// <summary>
/// Renders a standalone <c>::view</c> as a T-SQL <c>CREATE VIEW</c>, into <c>dbo/Views_gen/{Name}.sql</c>
/// beside the FullViews.
/// </summary>
/// <remarks>
/// <para>
/// Each relation is aliased by its own name (<c>[Customer]</c>), so a <c>Relation.field</c> in the model
/// reads the same in the SQL. Joins are <c>INNER JOIN</c>s on the resolved terms. <c>@rollup</c> is the
/// FullView's correlated subquery, correlated on the <c>from</c> model's key.
/// </para>
/// <para>
/// <c>where</c> and <c>@computed</c> follow the FullView's expression contract: identifiers become
/// PascalCase columns, string literals are kept — the language does not define the expression
/// dialect, so the text is otherwise passed through. A <c>Relation.field</c> naming one of the
/// view's relations is qualified first. A computed column may read the columns before it, so the
/// view is layered (one CTE per computed column) and the final select lists the columns in
/// declaration order. <c>order_by</c> is not emitted: a view has no order, and T-SQL refuses one
/// without <c>TOP</c>.
/// </para>
/// </remarks>
public static class StandaloneViewRenderer
{
    private const string Header = "-- # Code generated by \"mdd-booster\"; DO NOT EDIT.";

    public static string Render(
        ResolvedView view,
        string schema,
        IReadOnlyDictionary<string, IReadOnlySet<string>> derivedFieldsByModel)
    {
        ArgumentNullException.ThrowIfNull(view);
        ArgumentException.ThrowIfNullOrWhiteSpace(schema);
        ArgumentNullException.ThrowIfNull(derivedFieldsByModel);

        var fromModel = view.From.Model;
        var projected = new List<(string Expr, string Alias)>();
        var computed = new List<(string Expr, string Alias)>();
        foreach (var column in view.Columns)
        {
            var alias = NameCasing.ToPascalCase(column.Name);
            switch (column)
            {
                case ViewFromColumn from:
                    projected.Add((Column(from.Source), alias));
                    break;
                case ViewRollupColumn rollup:
                    projected.Add((FullViewRenderer.RenderRollupSubquery(
                        rollup.Rollup, schema, Alias(view.From), TargetKey.PkColumn(fromModel!), derivedFieldsByModel,
                        targetSoftDeletes: SoftDelete.IsEnabled(rollup.Target)), alias));
                    break;
                case ViewComputedColumn c:
                    computed.Add((Expression(ExpressionSelection.Select(c.Computed, SqlDialect.SqlServer)?.Text ?? string.Empty, view), alias));
                    break;
            }
        }

        var body = new StringBuilder();
        var indent = computed.Count == 0 ? "" : "    ";
        body.Append(indent).AppendLine("SELECT");
        for (var i = 0; i < projected.Count; i++)
        {
            body.Append(indent).Append("    ").Append(projected[i].Expr).Append(" AS [").Append(projected[i].Alias).Append(']');
            body.AppendLine(i < projected.Count - 1 ? "," : "");
        }
        body.Append(indent).Append("FROM ").AppendLine(Source(view, view.From, schema, derivedFieldsByModel));
        foreach (var join in view.Joins)
        {
            body.Append(indent).Append("INNER JOIN ").Append(Source(view, join.Target, schema, derivedFieldsByModel))
                .Append(" ON ")
                .AppendLine(string.Join(" AND ", join.On.Select(t => $"{Column(t.Left)} = {Column(t.Right)}")));
        }
        if (view.WhereFor(SqlDialect.SqlServer) is { } where)
            body.Append(indent).Append("WHERE ").AppendLine(Expression(where.Text, view));
        if (view.GroupBy.Count > 0)
            body.Append(indent).Append("GROUP BY ").AppendLine(string.Join(", ", view.GroupBy.Select(Column)));

        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.Append("CREATE VIEW [").Append(schema).Append("].[").Append(view.Name).AppendLine("]");
        sb.AppendLine("AS");
        if (computed.Count == 0)
        {
            sb.Append(body);
        }
        else
        {
            // r = the projected columns; then one layer per computed column, each able to read
            // every column before it; the final select restores declaration order.
            sb.AppendLine("WITH");
            sb.AppendLine("r AS (");
            sb.Append(body);
            var previous = "r";
            for (var i = 0; i < computed.Count; i++)
            {
                var layer = "c" + i;
                sb.AppendLine("),");
                sb.Append(layer).AppendLine(" AS (");
                sb.Append("    SELECT ").Append(previous).Append(".*, ").Append(computed[i].Expr)
                  .Append(" AS [").Append(computed[i].Alias).AppendLine("]");
                sb.Append("    FROM ").AppendLine(previous);
                previous = layer;
            }
            sb.AppendLine(")");
            sb.Append("SELECT ")
              .Append(string.Join(", ", view.Columns.Select(c => "[" + NameCasing.ToPascalCase(c.Name) + "]")))
              .Append(" FROM ").AppendLine(previous);
        }
        sb.AppendLine("GO");
        return sb.ToString();
    }

    private static string Alias(ViewRelation relation) => "[" + relation.Name + "]";

    private static string Column(ViewColumnRef reference) =>
        $"{Alias(reference.Relation)}.[{NameCasing.ToPascalCase(reference.Column)}]";

    private static string Source(
        ResolvedView view, ViewRelation relation, string schema, IReadOnlyDictionary<string, IReadOnlySet<string>> derived)
    {
        var name = StandaloneViewSources.SourceOf(view, relation, derived) switch
        {
            StandaloneViewSourceKind.FullView => relation.Name + "FullView",
            StandaloneViewSourceKind.UdView => relation.Name + "UdView",
            _ => relation.Name,
        };
        return $"[{schema}].[{name}] AS {Alias(relation)}";
    }

    /// <summary>
    /// The FullView expression contract, after qualifying each <c>Relation.field</c> that names one of
    /// the view's relations — the normalizer leaves bracketed text alone.
    /// </summary>
    private static string Expression(string text, ResolvedView view)
    {
        var relations = new[] { view.From }.Concat(view.Joins.Select(j => j.Target)).Select(r => r.Name);
        foreach (var relation in relations)
        {
            text = Regex.Replace(text, $@"(?<![\w.\[])\b{Regex.Escape(relation)}\.([a-z][a-z0-9_]*)\b",
                m => $"[{relation}].[{NameCasing.ToPascalCase(m.Groups[1].Value)}]");
        }
        return FullViewRenderer.NormalizeComputedExpression(text);
    }
}
