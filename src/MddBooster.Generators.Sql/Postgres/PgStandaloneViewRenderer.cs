using MddBooster.Core.Types;

namespace MddBooster.Generators.Sql.Postgres;

/// <summary>
/// Renders a standalone <c>::view</c> as a PostgreSQL <c>CREATE VIEW</c>, into
/// <c>views_gen/{snake_name}.sql</c>. The T-SQL renderer is the reference — the same relations, sources, joins,
/// rollups, group keys and expressions (the portable subset translated, or the <c>postgresql</c> platform expression),
/// in this dialect's names.
/// </summary>
public static class PgStandaloneViewRenderer
{
    private const string Header = "-- # Code generated by \"mdd-booster\"; DO NOT EDIT.";

    /// <param name="tableNameMap">Model → table name.</param>
    /// <param name="fullViewNameMap">Model → FullView name.</param>
    /// <param name="viewNameMap">Standalone view → view name, this one included.</param>
    public static string Render(
        ResolvedView view,
        string schema,
        IReadOnlyDictionary<string, string> tableNameMap,
        IReadOnlyDictionary<string, string> fullViewNameMap,
        IReadOnlyDictionary<string, string> viewNameMap,
        IReadOnlyDictionary<string, IReadOnlySet<string>> derivedFieldsByModel)
    {
        ArgumentNullException.ThrowIfNull(view);
        ArgumentException.ThrowIfNullOrWhiteSpace(schema);

        var aliases = new Dictionary<string, string>(StringComparer.Ordinal);
        string Alias(ViewRelation r) => aliases[r.Name];
        foreach (var relation in new[] { view.From }.Concat(view.Joins.Select(j => j.Target)))
            aliases[relation.Name] = relation.Kind == ViewRelationKind.Model ? tableNameMap[relation.Name] : viewNameMap[relation.Name];

        string Column(ViewColumnRef reference)
        {
            // A row version is the table's `xmin` system column — a view over the table carries it
            // under the field's name already (see PgFullViewRenderer.ProjectBaseColumn).
            if (reference.Relation.Kind == ViewRelationKind.Model
                && StandaloneViewSources.SourceOf(view, reference.Relation, derivedFieldsByModel) == StandaloneViewSourceKind.Table
                && reference.Relation.Model!.Fields.FirstOrDefault(f => f.Name == reference.Column) is { } field
                && M3lPrimitives.IsRowVersion(field))
                return $"{Alias(reference.Relation)}.xmin";
            return $"{Alias(reference.Relation)}.{reference.Column}";
        }

        string Source(ViewRelation relation)
        {
            var name = StandaloneViewSources.SourceOf(view, relation, derivedFieldsByModel) switch
            {
                StandaloneViewSourceKind.FullView => fullViewNameMap[relation.Name],
                StandaloneViewSourceKind.UdView => PgFullViewRenderer.UdViewNameOf(tableNameMap[relation.Name]),
                StandaloneViewSourceKind.Table => tableNameMap[relation.Name],
                _ => viewNameMap[relation.Name],
            };
            return $"{schema}.{name} AS {Alias(relation)}";
        }

        var columns = new List<string>();
        foreach (var column in view.Columns)
        {
            switch (column)
            {
                case ViewFromColumn from:
                    columns.Add($"{Column(from.Source)} AS {column.Name}");
                    break;
                case ViewRollupColumn rollup:
                    var key = ModelPrimaryKey.Find(view.From.Model!)
                        ?? throw new InvalidOperationException($"Model '{view.From.Name}' has no key to correlate a rollup on.");
                    columns.Add(PgFullViewRenderer.RenderRollupSubquery(
                        rollup.Rollup, schema, Alias(view.From), key.Name, tableNameMap, fullViewNameMap, derivedFieldsByModel,
                        targetSoftDeletes: SoftDelete.IsEnabled(rollup.Target)) + $" AS {column.Name}");
                    break;
                case ViewComputedColumn computed:
                    var selected = ExpressionSelection.Select(computed.Computed, SqlDialect.PostgreSql)
                        ?? throw new InvalidOperationException($"View column '{view.Name}.{column.Name}' has no PostgreSQL expression (MDD036).");
                    columns.Add($"{PostgresExpressions.Render(selected, Reference)} AS {column.Name}");
                    break;
            }
        }

        // `Relation.field` reads that relation's column; a bare name reads the view's `from`.
        string Reference(string name)
        {
            var dot = name.IndexOf('.', StringComparison.Ordinal);
            return dot > 0 && aliases.TryGetValue(name[..dot], out var alias)
                ? $"{alias}.{name[(dot + 1)..]}"
                : $"{Alias(view.From)}.{name}";
        }

        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.Append("CREATE VIEW ").Append(schema).Append('.').Append(viewNameMap[view.Name]).AppendLine(" AS");
        sb.AppendLine("SELECT");
        for (var i = 0; i < columns.Count; i++)
            sb.Append("    ").Append(columns[i]).AppendLine(i < columns.Count - 1 ? "," : "");
        sb.Append("FROM ").AppendLine(Source(view.From));
        foreach (var join in view.Joins)
        {
            sb.Append("INNER JOIN ").Append(Source(join.Target)).Append(" ON ")
              .AppendLine(string.Join(" AND ", join.On.Select(t => $"{Column(t.Left)} = {Column(t.Right)}")));
        }
        if (view.WhereFor(SqlDialect.PostgreSql) is { } where)
            sb.Append("WHERE ").AppendLine(PostgresExpressions.Render(where, Reference));
        if (view.GroupBy.Count > 0)
            sb.Append("GROUP BY ").AppendLine(string.Join(", ", view.GroupBy.Select(Column)));
        sb.Length -= Environment.NewLine.Length;
        sb.AppendLine(";");
        return sb.ToString();
    }
}
