using System.Text;
using System.Text.RegularExpressions;
using MddBooster.Core.Generation;
using MddBooster.Core.Naming;

namespace MddBooster.Generators.Sql;

/// <summary>
/// Writes the renames a model declares (<see cref="RenameSteps"/>) as run-once scripts for a schema tool's stage that
/// runs before its declarative comparison — so a renamed table or column keeps its rows instead of reading as a removal
/// plus an addition.
/// </summary>
/// <remarks>
/// <para>
/// <b>Append-only.</b> Each step is one file, <c>V{n}__rename_…sql</c>. A tool that runs such scripts once records
/// each by its file name and refuses one whose content changed after it ran, so a file this writer finds already in
/// the directory is never rewritten: a step whose file exists is skipped, and a new step takes the next number after
/// the highest in the directory (scripts written by hand there included). Content depends on the step alone, so a
/// file is the same bytes whenever it is written.
/// </para>
/// <para>
/// <b>Guarded.</b> Every pending script runs on every database, a new one too, and a declaration may stay in the
/// model long after its storage has moved. A statement runs only when the former name exists and the new one does
/// not; otherwise the script does nothing.
/// </para>
/// </remarks>
public sealed class PreScriptWriter(SqlDialect dialect, string schema, Func<string, string> tableName)
{
    private static readonly Regex Versioned = new(@"^V(?<version>\d+)__(?<slug>.+)\.sql$", RegexOptions.IgnoreCase);

    private const string Header = "-- # Code generated by \"mdd-booster\"; DO NOT EDIT.";

    /// <summary>
    /// The Sql targets' one entry: writes the set's declared renames to <paramref name="preScriptsPath"/>, or says
    /// that they are not acted on when no path is configured.
    /// </summary>
    /// <exception cref="GeneratorRefusalException">The path lies inside the project a schema tool reads as desired state.</exception>
    public static void Emit(
        GeneratorContext context, string? preScriptsPath, string projectRoot,
        SqlDialect dialect, string schema, Func<string, string> tableName)
    {
        ArgumentNullException.ThrowIfNull(context);
        var steps = RenameSteps.Of(context.Models);
        // Without a configured place the renames are not acted on; the build reports that before any target runs (MDD051).
        if (steps.Count == 0 || preScriptsPath is null) return;
        var directory = ResolvePlacement(context.WorkingDirectory, preScriptsPath, projectRoot)!;
        foreach (var file in new PreScriptWriter(dialect, schema, tableName).Write(directory, steps))
            Console.WriteLine($"[sql] 사전 스크립트: {file}");
    }

    /// <summary>
    /// The configured directory, resolved — checked before any target writes (a target's validation step).
    /// <see langword="null"/> when none is configured.
    /// </summary>
    /// <exception cref="GeneratorRefusalException">The path lies inside the project a schema tool reads as desired state.</exception>
    public static string? ResolvePlacement(string workingDirectory, string? preScriptsPath, string projectRoot)
    {
        if (preScriptsPath is null) return null;
        var directory = ConfiguredPathResolver.Resolve(workingDirectory, preScriptsPath, "preScriptsPath");
        var root = Path.TrimEndingDirectorySeparator(projectRoot) + Path.DirectorySeparatorChar;
        if ((Path.TrimEndingDirectorySeparator(directory) + Path.DirectorySeparatorChar).StartsWith(root, StringComparison.OrdinalIgnoreCase))
        {
            throw new GeneratorRefusalException(GeneratorRefusalKind.Configuration,
                $"preScriptsPath '{preScriptsPath}' is inside projectPath — a schema tool reading the project as desired " +
                "state would read the rename scripts as schema. Put it beside the project (e.g. '../pre').");
        }
        return directory;
    }

    /// <summary>Writes the steps <paramref name="steps"/> that have no file in <paramref name="directory"/> yet.</summary>
    /// <returns>The file names written, in order.</returns>
    public IReadOnlyList<string> Write(string directory, IReadOnlyList<RenameSteps.Step> steps)
    {
        ArgumentNullException.ThrowIfNull(steps);
        if (steps.Count == 0) return [];
        Directory.CreateDirectory(directory);

        var existing = Directory.EnumerateFiles(directory, "*.sql", SearchOption.TopDirectoryOnly)
            .Select(f => Versioned.Match(Path.GetFileName(f)))
            .Where(m => m.Success)
            .ToList();
        var slugs = existing.Select(m => m.Groups["slug"].Value).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var next = existing.Select(m => int.Parse(m.Groups["version"].Value, System.Globalization.CultureInfo.InvariantCulture))
            .DefaultIfEmpty(0).Max() + 1;

        var written = new List<string>();
        foreach (var step in steps)
        {
            var slug = Slug(step);
            if (!slugs.Add(slug)) continue;
            var fileName = $"V{next:0000}__{slug}.sql";
            File.WriteAllText(Path.Combine(directory, fileName), Render(step));
            written.Add(fileName);
            next++;
        }
        return written;
    }

    /// <summary>The step's identity across builds — what the file name carries after its number.</summary>
    public static string Slug(RenameSteps.Step step) => step.Kind == RenameSteps.Kind.Table
        ? $"rename_table_{step.From}_to_{step.To}"
        : $"rename_column_{step.Model}_{step.From}_to_{step.To}";

    /// <summary>The script for <paramref name="step"/> in this writer's dialect.</summary>
    public string Render(RenameSteps.Step step)
    {
        var sb = new StringBuilder();
        sb.Append(Header).Append('\n');
        sb.Append("-- ").Append(step.Kind == RenameSteps.Kind.Table ? "Model" : "Field").Append(' ')
          .Append(step.Kind == RenameSteps.Kind.Table ? step.To : $"{step.Model}.{step.To}")
          .Append(" @renamed_from(").Append(step.From).Append(") — runs only while the former name exists.\n");
        sb.Append(dialect == SqlDialect.PostgreSql ? RenderPostgres(step) : RenderSqlServer(step));
        return sb.ToString();
    }

    private string RenderSqlServer(RenameSteps.Step step)
    {
        var sb = new StringBuilder();
        string table;
        string renamedTable; // the table as it is named before the rename — what a schema-bound view references
        if (step.Kind == RenameSteps.Kind.Table)
        {
            renamedTable = $"[{schema}].[{step.From}]";
            table = $"[{schema}].[{step.To}]";
            sb.Append($"IF OBJECT_ID(N'{Escape(renamedTable)}', N'U') IS NOT NULL AND OBJECT_ID(N'{Escape(table)}', N'U') IS NULL\n")
              .Append("BEGIN\n");
            AppendDropSchemaBoundViews(sb, renamedTable);
            sb.Append($"    EXEC sp_rename N'{Escape(renamedTable)}', N'{Escape(step.To)}';\n")
              .Append("END\n");
        }
        else
        {
            table = renamedTable = $"[{schema}].[{step.Model}]";
            var oldColumn = Core.Naming.NameCasing.ToPascalCase(step.From);
            var newColumn = Core.Naming.NameCasing.ToPascalCase(step.To);
            sb.Append($"IF COL_LENGTH(N'{Escape(table)}', N'{Escape(oldColumn)}') IS NOT NULL AND COL_LENGTH(N'{Escape(table)}', N'{Escape(newColumn)}') IS NULL\n")
              .Append("BEGIN\n");
            AppendDropSchemaBoundViews(sb, table);
            sb.Append($"    EXEC sp_rename N'{Escape($"{table}.[{oldColumn}]")}', N'{Escape(newColumn)}', N'COLUMN';\n")
              .Append("END\n");
        }
        // The names this generator gave the table's constraints and indexes carry the table's and the column's names.
        // A constraint (a unique or check constraint) is renamed as an object, an index (a filtered unique one too)
        // as an index of the table.
        foreach (var (oldName, newName) in GeneratedNameRenames(step, postgres: false))
        {
            sb.Append($"IF EXISTS (SELECT 1 FROM sys.objects WHERE name = N'{Escape(oldName)}' AND parent_object_id = OBJECT_ID(N'{Escape(table)}'))\n")
              .Append($"    EXEC sp_rename N'{Escape($"[{schema}].[{oldName}]")}', N'{Escape(newName)}', N'OBJECT';\n")
              .Append($"ELSE IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'{Escape(oldName)}' AND object_id = OBJECT_ID(N'{Escape(table)}'))\n")
              .Append($"    EXEC sp_rename N'{Escape($"{table}.[{oldName}]")}', N'{Escape(newName)}', N'INDEX';\n");
        }
        return sb.ToString();
    }

    /// <summary>
    /// SQL Server refuses to rename a table or a column a schema-bound view depends on (Msg 15336) — and this generator
    /// writes one for a model with an <c>@indexed</c> rollup. The views that bind to the table are dropped first, inside
    /// the rename's guard: a view holds no data, and the declarative stage that follows creates it again from the
    /// desired state (with the index it declares there). A view that a second schema-bound view binds to in turn is
    /// not unwound; its drop fails and the script stops with SQL Server's own message.
    /// </summary>
    private static void AppendDropSchemaBoundViews(StringBuilder sb, string table)
    {
        sb.Append("    DECLARE @bound nvarchar(max) = (SELECT STRING_AGG(N'DROP VIEW ' + QUOTENAME(OBJECT_SCHEMA_NAME(v.referencing_id)) ")
          .Append("+ N'.' + QUOTENAME(OBJECT_NAME(v.referencing_id)) + N';', N' ') FROM (SELECT DISTINCT d.referencing_id ")
          .Append("FROM sys.sql_expression_dependencies d JOIN sys.views w ON w.object_id = d.referencing_id ")
          .Append($"WHERE d.referenced_id = OBJECT_ID(N'{Escape(table)}') AND d.is_schema_bound_reference = 1) v);\n")
          .Append("    IF @bound IS NOT NULL EXEC sys.sp_executesql @bound;\n");
    }

    private string RenderPostgres(RenameSteps.Step step)
    {
        var sb = new StringBuilder("DO $$\nBEGIN\n");
        string table;
        if (step.Kind == RenameSteps.Kind.Table)
        {
            var from = Core.Naming.PostgresIdentifiers.ToSnakeCase(step.From);
            table = tableName(step.To);
            sb.Append($"    IF to_regclass('{schema}.{from}') IS NOT NULL AND to_regclass('{schema}.{table}') IS NULL THEN\n")
              .Append($"        ALTER TABLE {schema}.{from} RENAME TO {table};\n")
              .Append("    END IF;\n");
        }
        else
        {
            table = tableName(step.Model);
            sb.Append("    IF EXISTS (SELECT 1 FROM information_schema.columns ")
              .Append($"WHERE table_schema = '{schema}' AND table_name = '{table}' AND column_name = '{step.From}')\n")
              .Append("       AND NOT EXISTS (SELECT 1 FROM information_schema.columns ")
              .Append($"WHERE table_schema = '{schema}' AND table_name = '{table}' AND column_name = '{step.To}') THEN\n")
              .Append($"        ALTER TABLE {schema}.{table} RENAME COLUMN {step.From} TO {step.To};\n")
              .Append("    END IF;\n");
        }
        // The names this generator gave the table's constraints and indexes carry the table's and the column's names.
        foreach (var (oldName, newName) in GeneratedNameRenames(step, postgres: true))
        {
            sb.Append("    IF EXISTS (SELECT 1 FROM pg_constraint c JOIN pg_class t ON t.oid = c.conrelid ")
              .Append("JOIN pg_namespace n ON n.oid = t.relnamespace ")
              .Append($"WHERE n.nspname = '{schema}' AND t.relname = '{table}' AND c.conname = '{oldName}') THEN\n")
              .Append($"        ALTER TABLE {schema}.{table} RENAME CONSTRAINT {oldName} TO {newName};\n")
              .Append($"    ELSIF to_regclass('{schema}.{oldName}') IS NOT NULL THEN\n")
              .Append($"        ALTER INDEX {schema}.{oldName} RENAME TO {newName};\n")
              .Append("    END IF;\n");
        }
        return sb.Append("END $$;\n").ToString();
    }

    /// <summary>
    /// The generated constraint and index names the step changes, old and new (<see cref="GeneratedObjectNames"/>) —
    /// a table step changes the owner token of every single-column name (and PostgreSQL's primary key); a column step
    /// changes the column token. Each is renamed only if it exists, so naming a kind the table does not have is
    /// harmless. Names the model gives (an <c>### Indexes</c> item's) and multi-column names are not derived here.
    /// </summary>
    private IEnumerable<(string Old, string New)> GeneratedNameRenames(RenameSteps.Step step, bool postgres)
    {
        var kinds = postgres
            ? new[] { GeneratedObjectNames.Kind.ForeignKey, GeneratedObjectNames.Kind.Unique, GeneratedObjectNames.Kind.Index, GeneratedObjectNames.Kind.Check }
            : new[] { GeneratedObjectNames.Kind.Unique, GeneratedObjectNames.Kind.Index, GeneratedObjectNames.Kind.Check };
        string Column(string field) => postgres ? field : Core.Naming.NameCasing.ToPascalCase(field);
        var seen = new HashSet<string>(StringComparer.Ordinal);

        if (step.Kind == RenameSteps.Kind.Table)
        {
            var oldOwner = postgres ? Core.Naming.PostgresIdentifiers.ToSnakeCase(step.From) : step.From;
            var newOwner = postgres ? tableName(step.To) : step.To;
            if (postgres)
                yield return (GeneratedObjectNames.For(true, GeneratedObjectNames.Kind.PrimaryKey, oldOwner),
                              GeneratedObjectNames.For(true, GeneratedObjectNames.Kind.PrimaryKey, newOwner));
            foreach (var column in step.ColumnNames.Select(Column))
                foreach (var kind in kinds)
                {
                    var old = GeneratedObjectNames.For(postgres, kind, oldOwner, column);
                    if (seen.Add(old)) yield return (old, GeneratedObjectNames.For(postgres, kind, newOwner, column));
                }
            yield break;
        }

        var owner = postgres ? tableName(step.Model) : step.Model;
        foreach (var kind in kinds)
        {
            var old = GeneratedObjectNames.For(postgres, kind, owner, Column(step.From));
            if (seen.Add(old)) yield return (old, GeneratedObjectNames.For(postgres, kind, owner, Column(step.To)));
        }
    }

    private static string Escape(string text) => text.Replace("'", "''", StringComparison.Ordinal);
}
