using System.Text.RegularExpressions;
using M3L.Native;
using MddBooster.Core.Ast;
using MddBooster.Core.Semantic;
using MddBooster.Generators.TypeScript;
using static MddBooster.Tests.Generators.TypeScript.FormImportFixtures;

namespace MddBooster.Tests.Generators.TypeScript;

/// <summary>
/// <c>entity_description_gen.ts</c> is the reading side of an entity's fields: sections, labels, hints, kinds, references — read from
/// the same places the generated form and the field schema read them, so a screen built on it cannot call a field something else.
/// </summary>
public class TSEntityDescriptionRendererTests
{
    private static IReadOnlyList<ResolvedModel> LoadFixture(string name)
    {
        var ast = new M3lLoader().LoadFile(Path.Combine(AppContext.BaseDirectory, "fixtures", name));
        return new InterfaceResolver(ast).ResolveAll();
    }

    private static IReadOnlyList<ResolvedModel> LoadInline(string body)
    {
        var tmp = Path.Combine(Path.GetTempPath(), $"mdd-tsdesc-{Guid.NewGuid():N}.m3l.md");
        File.WriteAllText(tmp, "# Namespace: test\n\n" + body);
        try
        {
            var ast = new M3lLoader().LoadFile(tmp);
            return new InterfaceResolver(ast).ResolveAll();
        }
        finally { File.Delete(tmp); }
    }

    private static readonly IReadOnlySet<string> LevelEnum = new HashSet<string> { "Level" };

    private const string OrderModel = """
        ## Level ::enum
        - low: "낮음"
        - high: "높음"

        ## Timestampable ::interface
        - created_at: timestamp = now()
        - updated_at: timestamp = now()

        ---

        ## Customer : Timestampable
        - id: identifier @pk @generated
        - name(고객 상호): string(50) @not_null "고객 이름"

        ## Order : Timestampable
        - id: identifier @pk @generated
        - number(전표번호): string(30) @not_null @group("기본") @help("예: C-0001")
        - customer_id: identifier @reference(Customer) @not_null @group("기본")
        - level: Level @not_null @group("진행")
        - total: decimal(12,2) @group("진행")
        - labels: string[]
        - secret: string @internal
        - customer_name: string @lookup(customer_id.name)
        - item_count: integer @rollup(OrderItem.order_id, count)

        ## OrderItem : Timestampable
        - id: identifier @pk @generated
        - order_id: identifier @reference(Order) @not_null
        """;

    private static string EntityBlock(string rendered, string entity)
    {
        var start = rendered.IndexOf($"\n  {entity}: {{", StringComparison.Ordinal);
        Assert.True(start >= 0, $"no entry for {entity}");
        var end = rendered.IndexOf("\n  },", start, StringComparison.Ordinal);
        return rendered[start..end];
    }

    [Fact]
    public void Starts_with_the_generated_header_and_is_checked_against_its_own_type()
    {
        var result = TSEntityDescriptionRenderer.RenderAll(LoadInline(OrderModel), LevelEnum);

        Assert.StartsWith("// <auto-generated>", result);
        Assert.Contains("} as const satisfies Record<string, EntityDescription>", result);
    }

    [Fact]
    public void A_field_carries_its_label_its_hint_and_its_kind()
    {
        var order = EntityBlock(TSEntityDescriptionRenderer.RenderAll(LoadInline(OrderModel), LevelEnum), "Order");

        // `(전표번호)` is the short label; `@help` is the hint — the two the model keeps apart stay apart.
        Assert.Contains("{ name: 'Number', label: '전표번호', hint: '예: C-0001', kind: 'text' }", order);
        // No label was written: the field's name stands in, as it does on the form.
        Assert.Contains("{ name: 'Total', label: 'Total', kind: 'number' }", order);
    }

    [Fact]
    public void A_reference_names_the_entity_it_points_at_and_an_enum_field_names_its_type()
    {
        var order = EntityBlock(TSEntityDescriptionRenderer.RenderAll(LoadInline(OrderModel), LevelEnum), "Order");

        Assert.Contains("{ name: 'CustomerId', label: 'CustomerId', kind: 'reference', reference: 'Customer' }", order);
        Assert.Contains("{ name: 'Level', label: 'Level', kind: 'enum', enum: 'Level' }", order);
    }

    [Fact]
    public void A_lookup_names_the_reference_it_reads_through_and_borrows_the_label_it_reads()
    {
        var order = EntityBlock(TSEntityDescriptionRenderer.RenderAll(LoadInline(OrderModel), LevelEnum), "Order");

        Assert.Contains(
            "{ name: 'CustomerName', label: '고객 상호', kind: 'text', via: 'CustomerId', derived: 'lookup', readOnly: true }", order);
        Assert.Contains("{ name: 'ItemCount', label: 'ItemCount', kind: 'number', derived: 'rollup', readOnly: true }", order);
    }

    [Fact]
    public void A_list_field_is_marked_and_the_timestamps_every_entity_inherits_are_read_only()
    {
        var order = EntityBlock(TSEntityDescriptionRenderer.RenderAll(LoadInline(OrderModel), LevelEnum), "Order");

        Assert.Contains("{ name: 'Labels', label: 'Labels', kind: 'text', list: true }", order);
        Assert.Contains("{ name: 'CreatedAt', label: 'CreatedAt', kind: 'datetime', readOnly: true }", order);
    }

    [Fact]
    public void The_primary_key_and_an_internal_field_are_not_described()
    {
        var order = EntityBlock(TSEntityDescriptionRenderer.RenderAll(LoadInline(OrderModel), LevelEnum), "Order");

        Assert.DoesNotContain("name: 'Id'", order);
        Assert.DoesNotContain("Secret", order);
    }

    [Fact]
    public void Nothing_here_says_what_a_person_may_type_that_is_the_field_schemas()
    {
        var result = TSEntityDescriptionRenderer.RenderAll(LoadInline(OrderModel), LevelEnum);

        // `number` is `string(30) @not_null` and `total` is `decimal(12,2)`: the schema reports a length and a requirement for
        // them; the description does not.
        Assert.DoesNotContain("required", result);
        Assert.DoesNotContain("maxLength", result);
        Assert.DoesNotContain("min:", result);
        Assert.DoesNotContain("max:", result);
    }

    [Fact]
    public void A_field_carries_the_same_label_here_and_in_the_field_schema()
    {
        var models = LoadInline(OrderModel);

        var description = EntityBlock(TSEntityDescriptionRenderer.RenderAll(models, LevelEnum), "Order");
        var schema = TSFieldSchemaRenderer.RenderAll(models);

        // The label the lookup borrows comes from one function; both outputs show it.
        Assert.Contains("label: '고객 상호'", description);
        Assert.Contains("CustomerName: { label: '고객 상호', derived: 'lookup', readOnly: true },", schema);
    }

    [Fact]
    public void The_sections_are_the_forms_sections_in_the_forms_order()
    {
        var models = LoadFixture("order-with-group.m3l.md");

        var description = EntityBlock(TSEntityDescriptionRenderer.RenderAll(models, new HashSet<string> { "Priority", "Mode" }), "OrderItem");
        var form = TSFormRenderer.RenderAll(models, [], TestImports)["OrderItem"];

        var described = Regex.Matches(description, @"title: '([^']+)'").Select(m => m.Groups[1].Value).ToArray();
        var rendered = Regex.Matches(form, "<FormSection title=\"([^\"]+)\"").Select(m => m.Groups[1].Value).ToArray();

        Assert.Equal(["기본", "상세", "기타"], rendered);
        Assert.Equal(rendered, described);
    }

    [Fact]
    public void A_model_with_no_group_at_all_has_one_untitled_section()
    {
        var models = LoadInline("""
            ## Note
            - id: identifier @pk @generated
            - body: text "본문"
            """);

        var note = EntityBlock(TSEntityDescriptionRenderer.RenderAll(models, new HashSet<string>()), "Note");

        Assert.DoesNotContain("title:", note);
        Assert.Contains("{ name: 'Body', label: '본문', kind: 'text' }", note);
    }
}
