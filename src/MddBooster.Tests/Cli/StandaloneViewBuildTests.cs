using MddBooster.Cli.Commands;

namespace MddBooster.Tests.Cli;

/// <summary>
/// A standalone <c>::view</c> becomes a <c>CREATE VIEW</c> in both SQL dialects — the shapes the M3L
/// specification shows (§4.7.2–4.7.6) on SQL Server, and every expression-free shape on PostgreSQL,
/// which leaves a view with an expression out with <c>MDD029</c>.
/// </summary>
[Collection(ConsoleCaptureCollection.Name)]
public class StandaloneViewBuildTests
{
    private static string Scaffold(string model, string sqlTarget, out string root)
    {
        root = Path.Combine(Path.GetTempPath(), $"mdd-sview-{Guid.NewGuid():N}");
        var mddDir = Path.Combine(root, "mdd");
        Directory.CreateDirectory(mddDir);
        Directory.CreateDirectory(Path.Combine(root, "db"));
        File.WriteAllText(Path.Combine(mddDir, "tables.m3l.md"), model);
        File.WriteAllText(Path.Combine(mddDir, "mdd.json"), $$"""
            { "sources": ["./tables.m3l.md"], "targets": [ {{sqlTarget}} ] }
            """);
        return mddDir;
    }

    private static void Cleanup(string root)
    {
        try { Directory.Delete(root, recursive: true); } catch { }
    }

    private static string SpecFixture() =>
        File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "fixtures", "standalone-views.m3l.md"));

    private const string TsqlTarget = """{ "type": "Sql", "projectPath": "../db", "schema": "dbo", "emitSqlProj": false }""";
    private const string PgTarget = """{ "type": "Sql", "dialect": "postgres", "projectPath": "../db" }""";

    [Fact]
    public void An_aggregate_view_renders_its_rollups_and_group_on_SQL_Server()
    {
        var mddDir = Scaffold(SpecFixture(), TsqlTarget, out var root);
        try
        {
            Assert.Equal(0, new BuildCommand().Run(mddDir));
            var sql = File.ReadAllText(Path.Combine(root, "db", "dbo", "Views_gen", "CustomerStats.sql"));
            Assert.Equal(
                """
                -- # Code generated by "mdd-booster"; DO NOT EDIT.
                CREATE VIEW [dbo].[CustomerStats]
                AS
                SELECT
                    [Customer].[Name] AS [CustomerName],
                    [Customer].[Email] AS [Email],
                    (SELECT COUNT(*) FROM [dbo].[Order] WHERE [CustomerId] = [Customer].[Id]) AS [TotalOrders],
                    (SELECT ISNULL(SUM([TotalAmount]), 0) FROM [dbo].[Order] WHERE [CustomerId] = [Customer].[Id]) AS [TotalSpent],
                    (SELECT MAX([OrderedAt]) FROM [dbo].[Order] WHERE [CustomerId] = [Customer].[Id]) AS [LastOrder]
                FROM [dbo].[Customer] AS [Customer]
                GROUP BY [Customer].[Id], [Customer].[Name], [Customer].[Email]
                GO

                """.ReplaceLineEndings(),
                sql.ReplaceLineEndings());
        }
        finally { Cleanup(root); }
    }

    [Fact]
    public void A_join_view_and_a_nested_view_render_on_SQL_Server()
    {
        var mddDir = Scaffold(SpecFixture(), TsqlTarget, out var root);
        try
        {
            Assert.Equal(0, new BuildCommand().Run(mddDir));
            var views = Path.Combine(root, "db", "dbo", "Views_gen");

            var detail = File.ReadAllText(Path.Combine(views, "OrderDetail.sql"));
            Assert.Contains("FROM [dbo].[Order] AS [Order]", detail);
            Assert.Contains("INNER JOIN [dbo].[Customer] AS [Customer] ON [Order].[CustomerId] = [Customer].[Id]", detail);
            Assert.Contains("INNER JOIN [dbo].[OrderItem] AS [OrderItem] ON [Order].[Id] = [OrderItem].[OrderId]", detail);
            Assert.Contains("INNER JOIN [dbo].[Product] AS [Product] ON [OrderItem].[ProductId] = [Product].[Id]", detail);
            Assert.Contains("[Product].[Name] AS [ProductName]", detail);

            var nested = File.ReadAllText(Path.Combine(views, "BigSpenders.sql"));
            Assert.Contains("FROM [dbo].[CustomerStats] AS [CustomerStats]", nested);
            Assert.Contains("[CustomerStats].[TotalSpent] AS [TotalSpent]", nested);

            var active = File.ReadAllText(Path.Combine(views, "ActiveProducts.sql"));
            // The portable `true` is SQL Server's 1 — the engine refuses `= true` as an unknown column.
            Assert.Contains("WHERE [Product].[IsActive] = 1 AND [Product].[StockQuantity] > 0", active);
            Assert.DoesNotContain("ORDER BY", active);
        }
        finally { Cleanup(root); }
    }

    [Fact]
    public void A_computed_column_is_layered_and_the_columns_keep_their_order()
    {
        var mddDir = Scaffold("""
            # Namespace: test

            ## Client
            - id: identifier @pk @generated
            - name: string(100) @not_null

            ## Purchase
            - id: identifier @pk @generated
            - client_id: identifier @reference(Client)
            - amount: decimal(12,2) @not_null

            ## ClientAverage ::view
            ### Source
            - from: Client

            - client_name: string @from(Client.name)
            - average: decimal(12,2) @computed("spent / NULLIF(purchases, 0)")
            - purchases: integer @rollup(Purchase.client_id, count)
            - spent: decimal(12,2) @rollup(Purchase.client_id, sum(amount))
            """, TsqlTarget, out var root);
        try
        {
            Assert.Equal(0, new BuildCommand().Run(mddDir));
            var sql = File.ReadAllText(Path.Combine(root, "db", "dbo", "Views_gen", "ClientAverage.sql"));
            Assert.Contains("c0 AS (", sql);
            Assert.Contains("SELECT r.*, CAST([Spent] / NULLIF([Purchases], 0) AS DECIMAL(12,2)) AS [Average]", sql);
            Assert.Contains("SELECT [ClientName], [Average], [Purchases], [Spent] FROM c0", sql);
        }
        finally { Cleanup(root); }
    }

    private const string PgModel = """
        # Namespace: test

        ## Client
        - id: identifier @pk @generated
        - name: string(100) @not_null

        ## Purchase
        - id: identifier @pk @generated
        - client_id: identifier @reference(Client)
        - amount: decimal(12,2) @not_null

        ## ClientTotals ::view
        ### Source
        - from: Client
        - group_by: [Client.id, Client.name]

        - client_name: string @from(Client.name)
        - purchases: integer @rollup(Purchase.client_id, count)
        - spent: decimal(12,2) @rollup(Purchase.client_id, sum(amount))

        ## PurchaseLines ::view
        ### Source
        - from: Purchase
        - join: Client on Purchase.client_id = Client.id

        - amount: decimal(12,2) @from(Purchase.amount)
        - client_name: string @from(Client.name)

        ## BigPurchases ::view
        ### Source
        - from: Purchase
        - where: "amount > 100"

        - amount: decimal(12,2) @from(Purchase.amount)
        """;

    [Fact]
    public void Expression_free_views_render_on_PostgreSQL()
    {
        var mddDir = Scaffold(PgModel, PgTarget, out var root);
        try
        {
            Assert.Equal(0, new BuildCommand().Run(mddDir));
            var views = Path.Combine(root, "db", "views_gen");
            Assert.Equal(
                """
                -- # Code generated by "mdd-booster"; DO NOT EDIT.
                CREATE VIEW public.client_totals AS
                SELECT
                    client.name AS client_name,
                    (SELECT COUNT(*) FROM public.purchase WHERE client_id = client.id) AS purchases,
                    (SELECT COALESCE(SUM(amount), 0) FROM public.purchase WHERE client_id = client.id) AS spent
                FROM public.client AS client
                GROUP BY client.id, client.name;

                """.ReplaceLineEndings(),
                File.ReadAllText(Path.Combine(views, "client_totals.sql")).ReplaceLineEndings());
            Assert.Contains(
                "INNER JOIN public.client AS client ON purchase.client_id = client.id",
                File.ReadAllText(Path.Combine(views, "purchase_lines.sql")));
        }
        finally { Cleanup(root); }
    }

    [Fact]
    public void A_view_with_a_portable_expression_is_rendered_on_PostgreSQL()
    {
        // The filter is written in M3L's portable subset (§10.7), so this dialect translates it rather than leaving the
        // view out — before expressions had a defined language it could only skip it (MDD029).
        var mddDir = Scaffold(PgModel, PgTarget, out var root);
        using var stderr = new ConsoleErrorCapture(this);
        try
        {
            Assert.Equal(0, new BuildCommand().Run(mddDir));
            var sql = File.ReadAllText(Path.Combine(root, "db", "views_gen", "big_purchases.sql"));
            Assert.Contains("WHERE purchase.amount > 100", sql);
            Assert.DoesNotContain("MDD029", stderr.Text);
        }
        finally { Cleanup(root); }
    }

    /// <summary>
    /// A computed column reads the view's own projected columns — here two rollups — so on PostgreSQL, as on SQL Server, the
    /// projection becomes a CTE and each computed column a layer over it.
    /// </summary>
    [Fact]
    public void A_computed_view_column_reads_the_projected_row_on_PostgreSQL()
    {
        const string model = """
            # Namespace: live.views

            ## Client
            - id: identifier @pk @generated
            - name: string(100) @not_null

            ## Purchase
            - id: identifier @pk @generated
            - client_id: identifier @reference(Client)
            - amount: decimal(12,2) @not_null

            ## ClientAverage ::view
            ### Source
            - from: Client

            - client_name: string @from(Client.name)
            - purchases: integer @rollup(Purchase.client_id, count)
            - spent: decimal(12,2) @rollup(Purchase.client_id, sum(amount))
            - average: decimal(12,2) @computed("spent / NULLIF(purchases, 0)")
            """;
        var mddDir = Scaffold(model, PgTarget, out var root);
        try
        {
            Assert.Equal(0, new BuildCommand().Run(mddDir));
            var sql = File.ReadAllText(Path.Combine(root, "db", "views_gen", "client_average.sql"));
            Assert.Contains("WITH r AS (", sql);
            Assert.Contains("c1 AS (SELECT r.*, CAST(spent / nullif(purchases, 0) AS numeric(12,2)) AS average FROM r)", sql);
            Assert.Contains("SELECT * FROM c1;", sql);
        }
        finally { Cleanup(root); }
    }

    [Fact]
    public void Without_a_Sql_target_the_build_says_the_views_are_not_generated()
    {
        var mddDir = Scaffold(PgModel, """{ "type": "Model", "projectPath": "../db", "namespace": "T.Entities", "dbContextName": "TDb" }""", out var root);
        using var stderr = new ConsoleErrorCapture(this);
        try
        {
            new BuildCommand().Run(mddDir);
            Assert.Contains("standalone 뷰 3개의 CREATE VIEW 를 생성하는 타깃이 없습니다", stderr.Text);
        }
        finally { Cleanup(root); }
    }
}
