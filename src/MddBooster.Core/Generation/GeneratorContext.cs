using M3L.Native;
using MddBooster.Core.Semantic;

namespace MddBooster.Core.Generation;

public sealed class GeneratorContext
{
    public required IReadOnlyList<ResolvedModel> Models { get; init; }
    public required string WorkingDirectory { get; init; }

    /// <summary>
    /// Top-level enum declarations collected from every M3L source. Referenced
    /// by entity fields via their <c>Type</c> string (e.g. a field typed
    /// <c>OrderStatus</c> refers to the enum of the same name). Generators use
    /// this list to emit C# enum files, SQL CHECK constraints, and to route
    /// enum-typed fields in the type mappers.
    /// </summary>
    public IReadOnlyList<EnumNode> Enums { get; init; } = Array.Empty<EnumNode>();

    /// <summary>
    /// Standalone <c>::view</c> declarations that resolved completely (<see cref="ViewResolver"/>),
    /// in dependency order — a view after every view it reads. A view that did not resolve is not
    /// here; the build has already said why.
    /// </summary>
    public IReadOnlyList<ResolvedView> Views { get; init; } = Array.Empty<ResolvedView>();

    /// <summary>
    /// The views this build serves as read models (<see cref="ViewReadModels"/>): keyed, not <c>@internal</c>, and
    /// generated by every SQL target of the build — a view a dialect leaves out has nothing for an entity to map to.
    /// The Model target emits an entity for each, the Api target a read-only set.
    /// </summary>
    public IReadOnlyList<ResolvedView> ReadViews { get; init; } = Array.Empty<ResolvedView>();

    /// <summary>
    /// The sources read but not generated (<see cref="ReferenceSet"/>). <see cref="Models"/>, <see cref="Enums"/> and
    /// the views hold their declarations too — they are what names resolve against; a generator emits only the
    /// <c>Generated…</c> ones.
    /// </summary>
    public ReferenceSet References { get; init; } = ReferenceSet.None;

    /// <summary>The models this build emits: every model but the referenced ones.</summary>
    public IReadOnlyList<ResolvedModel> GeneratedModels => References.IsEmpty ? Models : Models.Where(m => !References.Contains(m)).ToList();

    public IReadOnlyList<EnumNode> GeneratedEnums => References.IsEmpty ? Enums : Enums.Where(e => !References.Contains(e)).ToList();

    public IReadOnlyList<ResolvedView> GeneratedViews => References.IsEmpty ? Views : Views.Where(v => !References.Contains(v)).ToList();

    public IReadOnlyList<ResolvedView> GeneratedReadViews => References.IsEmpty ? ReadViews : ReadViews.Where(v => !References.Contains(v)).ToList();
}
