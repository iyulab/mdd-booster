using System.Text;
using M3L.Native;
using MddBooster.Core.Generation;
using MddBooster.Core.Naming;
using MddBooster.Core.Semantic;

namespace MddBooster.Generators.Api;

/// <summary>
/// Renders a single <c>ApiRegistration_gen.cs</c> file that wires every
/// generated entity pair into OData (EDM model) and GraphQL (HotChocolate
/// schema). The consumer project calls the generated static method once in
/// its composition root; the method shape matches the host framework's
/// <c>IyuMainServerOptions</c> API surface.
/// </summary>
/// <remarks>
/// The generated method signature is:
/// <code>
/// public static void RegisterGeneratedEntities(IyuMainServerOptions options)
/// </code>
/// For every model <c>Order</c>, the method body emits two lines:
/// <code>
/// options.ODataModel.AddEntityPair&lt;OrderExt, Order&gt;("Orders");
/// options.GraphQL.AddEntityPair&lt;OrderExt, Order&gt;("orders", "order");
/// </code>
/// Entity set names use <see cref="Pluralizer"/> to match the DbContext
/// convention; GraphQL query names are camelCase plural; mutation prefix is
/// camelCase singular (HotChocolate mutation field naming convention).
/// <para>
/// <c>surfaces</c> narrows that to the surfaces the deployment serves: without
/// <see cref="ApiSurfaces.GraphQL"/> no GraphQL line is written (and the runtime maps no
/// <c>/graphql</c> endpoint); without <see cref="ApiSurfaces.OData"/> no OData line or shared-key
/// declaration is written.
/// </para>
/// </remarks>
public static class ApiRegistrationRenderer
{
    private const string Header = "// <auto-generated> mdd-booster; DO NOT EDIT.</auto-generated>";

    public static string Render(
        IReadOnlyList<ResolvedModel> models,
        string ns,
        string? entitiesNamespace = null,
        string methodName = "RegisterGeneratedEntities",
        ApiSurfaces surfaces = ApiSurfaces.All,
        IReadOnlySet<string>? registeredElsewhere = null)
    {
        ArgumentNullException.ThrowIfNull(models);
        ArgumentException.ThrowIfNullOrWhiteSpace(ns);
        ArgumentException.ThrowIfNullOrWhiteSpace(methodName);
        if (surfaces == ApiSurfaces.None)
            throw new ArgumentException("At least one surface must be selected.", nameof(surfaces));
        var odata = surfaces.HasFlag(ApiSurfaces.OData);
        var graphql = surfaces.HasFlag(ApiSurfaces.GraphQL);

        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        // 엔티티는 using 임포트가 아니라 한정 이름으로 가리킨다 — 이유는 EntityTypeRef 참조.
        var entityPrefix = EntityTypeRef.PrefixFor(ns, entitiesNamespace);
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();
        sb.AppendLine("public static partial class ApiRegistration");
        sb.AppendLine("{");
        sb.Append("    public static void ").Append(methodName)
          .AppendLine("(IyuMainServerOptions options)");
        sb.AppendLine("    {");

        foreach (var model in models.OrderBy(m => m.Name, StringComparer.Ordinal))
        {
            // @internal 엔티티는 데이터 API(OData/GraphQL) 노출에서 제외한다. SQL 테이블·Ext 뷰·
            // C# 엔티티·EF DbSet 은 그대로 생성되지만 AddEntityPair 를 방출하지 않는다 —
            // 아이덴티티/인증 같은 인프라 엔티티(전용 엔드포인트로만 관리, 범용 CRUD·시크릿 컬럼
            // 노출 금지)를 위한 도메인 중립 knob.
            //
            // 이 제외가 **타입 도달성까지** 없애는가: 런타임은 read 타입만 스키마에 등록하고
            // (OData `EntitySet<TRead>` · GraphQL `ObjectType<TRead>`), write 타입은 어느 스키마에도
            // 넣지 않는다. read(Ext) 타입은 이제 다른 read 타입을 가리키는 navigation 을 갖는다
            // (1:1 · 참조 키 N:1) — 그래서 제외된 엔티티의 read 타입은 navigation 을 거쳐 컨벤션
            // 발견으로 되살아날 수 있고, 그것을 막는 것은 런타임의 경계다: 등록되지 않은 타입을
            // 가리키는 navigation 을 EDM 과 GraphQL 타입에서 빼고 `$expand` 를 거절한다(런타임
            // CHANGELOG — 이 생성기의 산출이 그 판 이전 런타임 위에 올라가면 안 되는 이유).
            // mutation 은 런타임에 배선돼 있지 않다 — 배선되면 write 타입이 input 타입으로 들어가
            // 이 판단을 다시 해야 한다.
            if (EntitySurface.IsInternal(model)) continue;

            var entity = NameCasing.ToPascalCase(model.Name);
            var setName = Pluralizer.Pluralize(entity);            // OData: PascalCase 복수 — DbSet 이름과 맞춘다
            var mutationPrefix = NameCasing.ToCamelCase(entity);    // e.g. "order"
            // camelCase 를 **먼저** 적용하고 복수화한다. 순서를 뒤집으면 두 글자 약어가 깨진다 —
            // Pluralize("QR")="QRs" 의 'R' 은 뒤에 소문자 's' 가 붙어 약어 연쇄가 끊기므로
            // camelCase 가 'R' 을 보존해 "qRs" 가 된다. 반대 순서는 "qr" → "qrs".
            // Pluralizer 는 접미 규칙만 쓰고 불규칙 복수 사전이 없어 camelCase 입력에도 안전하다.
            var queryName = Pluralizer.Pluralize(mutationPrefix);   // e.g. "orders"

            if (odata)
            {
                sb.Append("        options.ODataModel.AddEntityPair<")
                  .Append(entityPrefix).Append(entity).Append("Ext, ")
                  .Append(entityPrefix).Append(entity).Append(">(\"")
                  .Append(setName).AppendLine("\");");
            }
            if (graphql)
            {
                sb.Append("        options.GraphQL.AddEntityPair<")
                  .Append(entityPrefix).Append(entity).Append("Ext, ")
                  .Append(entityPrefix).Append(entity).Append(">(\"")
                  .Append(queryName).Append("\", \"").Append(mutationPrefix).AppendLine("\");");
            }
        }

        // @system 필드 — 애플리케이션 자신의 코드가 쓰는 칸(상태·행위자·저장소 키). 모델이 그 사실을 말했으므로
        // 제네릭 쓰기 경로에서 빼 달라는 선언을 여기서 낸다: 손으로 유지하는 목록은 칸을 더한 사람이 그 목록을
        // 기억할 때만 맞는다. 읽기 타입의 속성을 가리키므로 읽기 표면에 없는 칸(@internal)은 대상이 아니고,
        // 파생 칸과 행 버전은 런타임이 이미 쓰기에서 뺀다. 쓰기 경로는 OData 의 것이다.
        if (odata)
        {
            foreach (var model in models.OrderBy(m => m.Name, StringComparer.Ordinal))
            {
                if (EntitySurface.IsInternal(model)) continue;
                var systemFields = model.Fields
                    .Where(f => f.Kind == FieldKind.Stored)
                    .Where(f => FieldAuthorship.IsDeclaredSystem(f) && !EntitySurface.IsFieldInternal(f))
                    .Select(f => "x => x." + NameCasing.ToPascalCase(f.Name))
                    .ToList();
                if (systemFields.Count == 0) continue;

                sb.Append("        options.ODataModel.ExcludeFromWrite<")
                  .Append(entityPrefix).Append(NameCasing.ToPascalCase(model.Name)).Append("Ext>(")
                  .Append(string.Join(", ", systemFields)).AppendLine(");");
            }
        }

        // ::aspect(Base) 셋은 키가 자기 것이 아니다 — 행의 키가 곧 Base 행에 대한 참조다. 런타임은 그
        // 사실을 선언받아야 제네릭 쓰기 경로에서 «아무 Base 도 가리키지 않는 행»을 거절할 수 있다
        // (선언이 없으면 서버가 새 키를 만들어 고아 행을 쓰거나, 막는 일을 DB 제약에 맡긴다 — EF 모델로
        // 스키마를 만드는 소비자에겐 그 제약도 없다). 런타임은 등록되지 않은 셋을 가리키는 선언을
        // 거절하므로 모든 AddEntityPair 뒤에 둔다. Base 가 @internal 이면 가리킬 셋이 없어 내지 않는다.
        // 공유 키는 OData 쓰기 경로의 선언이다 — OData 를 내지 않으면 가리킬 셋도, 지킬 쓰기도 없다.
        //
        // 선언은 aspect 셋을 등록하는 쪽에 속한다. Base 는 같은 빌드의 다른 Api 타깃이 등록할 수 있다 —
        // 소유자로 가른 타깃에서 모듈의 aspect 가 베이스의 Base 에 붙는 모양이다. 그 경우에도 선언을 내고,
        // 런타임이 선언 시점에 Base 셋을 찾으므로 그 등록을 먼저 부르라고 생성물에 적는다(순서가 틀리면
        // 기동이 Base 셋 이름을 대며 실패한다 — 조용히 꺼지지 않는다).
        var registered = odata
            ? models.Where(m => !EntitySurface.IsInternal(m)).Select(m => m.Name).ToHashSet(StringComparer.Ordinal)
            : [];
        foreach (var model in models.OrderBy(m => m.Name, StringComparer.Ordinal))
        {
            if (!registered.Contains(model.Name)) continue;
            if (model.Source.Base is not { Kind: "aspect" } aspectOf) continue;
            var principalHere = registered.Contains(aspectOf.Model);
            if (!principalHere && registeredElsewhere?.Contains(aspectOf.Model) != true) continue;

            if (!principalHere)
            {
                sb.Append("        // '").Append(Pluralizer.Pluralize(NameCasing.ToPascalCase(aspectOf.Model)))
                  .AppendLine("' is registered by another generated registration; call that one first.");
            }

            sb.Append("        options.ODataModel.DeclareSharedKey(\"")
              .Append(Pluralizer.Pluralize(NameCasing.ToPascalCase(model.Name))).Append("\", \"")
              .Append(Pluralizer.Pluralize(NameCasing.ToPascalCase(aspectOf.Model))).AppendLine("\");");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

}
